fn base_items(
    include_low_mach_params: bool,
    include_mesh_fluxes: bool,
    eos_params: &[ParamSpec],
    structured: bool,
) -> Vec<Item> {
    let mut items = Vec::new();
    items.push(Item::Struct(vector2_struct()));
    items.push(Item::Struct(constants_struct(eos_params)));
    if include_low_mach_params {
        items.push(Item::Struct(low_mach_params_struct()));
    }
    if structured {
        assert!(
            !include_mesh_fluxes,
            "flux_module: mesh_fluxes binding requested for a STRUCTURED kernel \
             (no structured ALE model exists)"
        );
        items.push(Item::Struct(
            cfd2_codegen::solver::codegen::coupled_common::structured_grid_struct(),
        ));
        items.push(Item::Comment(
            "Group 0: Structured Cartesian grid (no connectivity)".to_string(),
        ));
        items.push(uniform_var(
            "grid",
            Type::Custom("StructuredGrid".to_string()),
            0,
            0,
        ));
        items.push(sg::structured_face_boundary_binding());
    } else {
        items.push(Item::Comment("Group 0: Mesh".to_string()));
        items.extend(mesh_bindings());
        if include_mesh_fluxes {
            // ALE volumetric mesh flux (owner-signed swept rate, zero-filled on a
            // static mesh). Group 0 / binding 8 — the same slot the unified
            // assembly binds it at, so fusion sees one consistent declaration.
            items.push(storage_var(
                "mesh_fluxes",
                Type::array(Type::F32),
                0,
                8,
                AccessMode::Read,
            ));
        }
    }
    items.push(Item::Comment("Group 1: Fields".to_string()));
    items.extend(state_bindings(include_low_mach_params));
    items.push(Item::Comment(
        "Group 2: Boundary conditions (per face x unknown)".to_string(),
    ));
    items.extend(boundary_bindings());
    items.push(Item::Function(bc_neighbor_scalar_fn()));
    items
}

fn bc_neighbor_scalar_fn() -> Function {
    Function::new(
        "bc_neighbor_scalar",
        vec![
            Param::new("interior", Type::F32, Vec::new()),
            Param::new("owner", Type::F32, Vec::new()),
            Param::new("kind", Type::U32, Vec::new()),
            Param::new("value", Type::F32, Vec::new()),
            Param::new("d_own", Type::F32, Vec::new()),
            Param::new("is_boundary", Type::Bool, Vec::new()),
        ],
        Some(Type::F32),
        Vec::new(),
        Block::new(vec![
            dsl::var_typed_expr("boundary", Type::F32, Some(Expr::ident("owner"))),
            dsl::if_block_expr(
                Expr::ident("kind").eq(Expr::from(1u32)),
                dsl::block(vec![dsl::assign_expr(
                    Expr::ident("boundary"),
                    Expr::ident("value"),
                )]),
                None,
            ),
            dsl::if_block_expr(
                Expr::ident("kind").eq(Expr::from(2u32)),
                dsl::block(vec![dsl::assign_expr(
                    Expr::ident("boundary"),
                    Expr::ident("owner") + Expr::ident("value") * Expr::ident("d_own"),
                )]),
                None,
            ),
            Stmt::Return(Some(dsl::select(
                Expr::ident("interior"),
                Expr::ident("boundary"),
                Expr::ident("is_boundary"),
            ))),
        ]),
    )
}

