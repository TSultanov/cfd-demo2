const GENERIC_COUPLED_WORKGROUP_SIZE: u32 = 64;

pub fn generate_generic_coupled_assembly_wgsl(
    system: &DiscreteSystem,
    slots: &ResolvedStateSlotsSpec,
    needs_gradients: bool,
    eos_params: &[ParamSpec],
) -> KernelWgsl {
    let coupled_stride = coupled_unknown_components(system).len() as u32;

    struct Dispatch<'a> {
        system: &'a DiscreteSystem,
        slots: &'a ResolvedStateSlotsSpec,
        needs_gradients: bool,
        eos_params: &'a [ParamSpec],
    }
    impl typed::DispatchByStride<KernelWgsl> for Dispatch<'_> {
        fn call<Ax: typed::CoupledAxis>(&self) -> KernelWgsl {
            let mut module = Module::new();
            module.push(Item::Comment(
                "GENERATED BY CFD2 CODEGEN (generic_coupled_assembly)".to_string(),
            ));
            module.push(Item::Comment("DO NOT EDIT MANUALLY".to_string()));
            module.extend(base_assembly_items(
                self.needs_gradients,
                false,
                self.eos_params,
            ));
            module.push(Item::Function(main_assembly_fn::<Ax>(
                self.system,
                self.slots,
            )));
            KernelWgsl::from(module)
        }
    }
    typed::dispatch_by_coupled_stride(
        coupled_stride,
        Dispatch {
            system,
            slots,
            needs_gradients,
            eos_params,
        },
    )
    .unwrap_or_else(|e| panic!("{e}"))
}

pub fn generate_generic_coupled_update_wgsl(
    system: &DiscreteSystem,
    slots: &ResolvedStateSlotsSpec,
    primitives: &[(u32, Expr)],
    apply_relaxation: bool,
    relaxation_requires_dtau: bool,
    eos_params: &[ParamSpec],
) -> KernelWgsl {
    let mut module = Module::new();
    module.push(Item::Comment(
        "GENERATED BY CFD2 CODEGEN (generic_coupled_update)".to_string(),
    ));
    module.push(Item::Comment("DO NOT EDIT MANUALLY".to_string()));
    module.extend(base_update_items(eos_params));
    module.push(Item::Function(main_update_fn(
        system,
        slots,
        primitives,
        apply_relaxation,
        relaxation_requires_dtau,
    )));
    KernelWgsl::from(module)
}

pub fn generate_generic_coupled_update_kernel_program(
    id: &str,
    system: &DiscreteSystem,
    slots: &ResolvedStateSlotsSpec,
    primitives: &[(u32, Expr)],
    apply_relaxation: bool,
    relaxation_requires_dtau: bool,
    eos_params: &[ParamSpec],
) -> Result<KernelProgram, String> {
    let items = base_update_items(eos_params);
    let bindings = kernel_bindings_from_items(&items)?;
    let main = main_update_fn(
        system,
        slots,
        primitives,
        apply_relaxation,
        relaxation_requires_dtau,
    );
    let (launch, consumed_stmts) = launch_from_update_statements(&main.body.stmts)?;
    let kernel_stmts = &main.body.stmts[consumed_stmts..];

    let mut program = KernelProgram::new(id, DispatchDomain::Cells, launch, bindings);
    program.indexing = vec![cfd2_ir::ast::Stmt::Let {
        name: "base".to_string(),
        ty: None,
        expr: cfd2_ir::ast::Expr::ident("idx") * cfd2_ir::ast::Expr::lit_u32(slots.stride as u32),
    }];
    program.body = kernel_stmts.to_vec();
    program.eos_params = eos_params.to_vec();
    Ok(program)
}

