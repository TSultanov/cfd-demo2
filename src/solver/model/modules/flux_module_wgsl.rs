fn face_stmts(
    resolver: &dyn OffsetResolver,
    flux_layout: &FluxLayout,
    face_channels: &ExplicitFaceChannelLiveness,
    flux_stride: u32,
    primitives: &HashMap<&str, &Expr>,
    spec: &FluxModuleKernelSpec,
    structured: bool,
) -> Vec<Stmt> {
    // The face index the FLUX is written to: unstructured is the physical face
    // `idx`; structured is the per-(cell,dir) slot `idx*4 + k` (== `sfd_face_id`),
    // matching what the structured assembly reads (`fluxes[(idx*4+k)*stride+c]`).
    let flux_face = |storage_rank: u32| {
        if structured {
            dsl::array_access_linear(
                "fluxes",
                Expr::ident("sfd_face_id"),
                flux_stride,
                storage_rank,
            )
        } else {
            dsl::array_access_linear(
                "fluxes",
                Expr::ident("idx"),
                flux_stride,
                storage_rank,
            )
        }
    };
    let mut body: Vec<Stmt> = Vec::new();
    if structured {
        // Neighbour centre from grid arithmetic (`sfd_other_*`); no wrap (the
        // structured grid is non-periodic here).
        body.push(dsl::var_typed_expr(
            "c_neigh_vec",
            Type::vec2_f32(),
            Some(sg::sfd_vec2("sfd_other_cx", "sfd_other_cy")),
        ));
    } else {
        body.push(dsl::let_expr(
            "c_neigh",
            dsl::array_access("cell_centers", Expr::ident("neigh_idx")),
        ));
        body.push(dsl::var_typed_expr(
            "c_neigh_vec",
            Type::vec2_f32(),
            Some(typed::VecExpr::<2>::from_xy_fields(Expr::ident("c_neigh")).expr()),
        ));
        // Periodic wrap: lift the neighbor center into the owner's frame across a seam face.
        // `face_wrap_shift` is zero on every non-periodic mesh, so this is a no-op there.
        body.push(dsl::assign_expr(
            Expr::ident("c_neigh_vec"),
            typed::VecExpr::<2>::from_expr(Expr::ident("c_neigh_vec"))
                .add(&typed::VecExpr::<2>::from_xy_fields(
                    Expr::ident("face_wrap_shift").index(Expr::ident("idx")),
                ))
                .expr(),
        ));
    }

    // Preserve the true neighbor-cell center even on boundary faces.
    //
    // For boundary faces, we sometimes override `c_neigh_vec` for interpolation convenience,
    // but geometry builtins (e.g. `CellToFace{Neighbor}`) should still reference the neighbor
    // cell center (which degenerates to the owner cell for boundary faces).
    body.push(dsl::let_typed_expr(
        "c_neigh_cell_vec",
        Type::vec2_f32(),
        Expr::ident("c_neigh_vec"),
    ));
    body.push(dsl::if_block_expr(
        Expr::ident("is_boundary"),
        dsl::block(vec![dsl::assign_expr(
            Expr::ident("c_neigh_vec"),
            Expr::ident("face_center_vec"),
        )]),
        None,
    ));

    // Match OpenFOAM's `surfaceInterpolation::weights()` (basicFvGeometryScheme):
    //   w = mag(Sf · (Cf - Cown)) / (mag(Sf · (Cf - Cown)) + mag(Sf · (Cnei - Cf)))
    //
    // Since `normal_vec` is unit-length and `Sf = area * normal_vec`, the area cancels.
    let d_own = dsl::abs(
        typed::VecExpr::<2>::from_expr(Expr::ident("face_center_vec"))
            .sub(&typed::VecExpr::<2>::from_expr(Expr::ident("c_owner_vec")))
            .dot(&typed::VecExpr::<2>::from_expr(Expr::ident("normal_vec"))),
    );
    body.push(dsl::let_expr("d_own", d_own));

    let d_neigh = dsl::abs(
        typed::VecExpr::<2>::from_expr(Expr::ident("c_neigh_vec"))
            .sub(&typed::VecExpr::<2>::from_expr(Expr::ident(
                "face_center_vec",
            )))
            .dot(&typed::VecExpr::<2>::from_expr(Expr::ident("normal_vec"))),
    );
    body.push(dsl::let_expr("d_neigh", d_neigh));
    body.push(dsl::let_expr(
        "total_dist",
        Expr::ident("d_own") + Expr::ident("d_neigh"),
    ));
    body.push(dsl::var_typed_expr("lambda", Type::F32, Some(0.5.into())));
    body.push(dsl::if_block_expr(
        Expr::ident("total_dist").gt(1e-6),
        dsl::block(vec![dsl::assign_expr(
            Expr::ident("lambda"),
            Expr::ident("d_neigh") / Expr::ident("total_dist"),
        )]),
        None,
    ));
    body.push(dsl::let_expr(
        "lambda_other",
        Expr::from(1.0) - Expr::ident("lambda"),
    ));

    let d_vec = typed::VecExpr::<2>::from_expr(Expr::ident("c_neigh_vec"))
        .sub(&typed::VecExpr::<2>::from_expr(Expr::ident("c_owner_vec")))
        .expr();
    body.push(dsl::let_typed_expr("d_vec", Type::vec2_f32(), d_vec));
    body.push(dsl::let_expr(
        "dist_proj",
        dsl::abs(
            typed::VecExpr::<2>::from_expr(Expr::ident("d_vec"))
                .dot(&typed::VecExpr::<2>::from_expr(Expr::ident("normal_vec"))),
        ),
    ));
    // Match unified pressure assembly's degeneracy fallback. For a valid FV
    // face `|n.d|` is the compact normal distance; on a near-tangent face the
    // flux and matrix must both fall back to `|d|` instead of using conductances
    // that differ by orders of magnitude.
    body.push(dsl::let_expr(
        "dist_euc",
        dsl::sqrt(
            Expr::ident("d_vec").field("x") * Expr::ident("d_vec").field("x")
                + Expr::ident("d_vec").field("y") * Expr::ident("d_vec").field("y"),
        ),
    ));
    body.push(dsl::var_typed_expr(
        "dist",
        Type::F32,
        Some(dsl::max("dist_euc", 1e-6)),
    ));
    body.push(dsl::if_block_expr(
        Expr::ident("dist_proj").gt(1e-6),
        dsl::block(vec![dsl::assign_expr(
            Expr::ident("dist"),
            Expr::ident("dist_proj"),
        )]),
        None,
    ));

    let mut state_keys = HashSet::new();
    collect_state_keys_from_flux_spec(spec, primitives, resolver, &mut state_keys);
    let (state_vars, state_var_stmts) =
        precompute_state_vars(resolver, flux_layout, &state_keys, structured);
    body.extend(state_var_stmts);
    let ctx = LowerCtx::new(resolver, primitives, flux_layout, state_vars, structured);
    let mut cse = CseBuilder::new("_cse_");
    let mut fcse = FaceCse::new();
    // Single-root lowerings without an eliminate scope keep the pre-memo
    // behavior (byte-identical output).
    let mut nocse = FaceCseScope::disabled();

    match spec {
        FluxModuleKernelSpec::ScalarReplicated { phi } => {
            let phi_expr = lower_scalar(phi, &ctx, &mut nocse);
            body.push(dsl::var_typed_expr("phi", Type::F32, Some(phi_expr)));

            for u_idx in 0..flux_stride {
                body.push(dsl::assign_expr(flux_face(u_idx), Expr::ident("phi")));
            }
        }
        FluxModuleKernelSpec::ScalarPerComponent { components, flux } => {
            if components.len() != flux_layout.components.len() {
                panic!("ScalarPerComponent spec component count does not match FluxLayout");
            }
            if flux.len() != components.len() {
                panic!("ScalarPerComponent spec arrays must match component count");
            }

            for (i, comp_name) in components.iter().enumerate() {
                let coupled_rank = flux_layout
                    .offset_for(comp_name)
                    .unwrap_or_else(|| panic!("missing flux layout component '{comp_name}'"));
                let Some(storage_rank) =
                    face_channels.storage_rank_for_coupled(coupled_rank)
                else {
                    continue;
                };
                let flux_expr = lower_scalar(&flux[i], &ctx, &mut nocse);
                body.push(dsl::assign_expr(flux_face(storage_rank), flux_expr));
            }
        }
        FluxModuleKernelSpec::CentralUpwind {
            reconstruction: _,
            components,
            u_left,
            u_right,
            flux_left,
            flux_right,
            a_plus,
            a_minus,
        } => {
            if components.len() != flux_layout.components.len() {
                panic!("CentralUpwind spec component count does not match FluxLayout");
            }
            if u_left.len() != components.len()
                || u_right.len() != components.len()
                || flux_left.len() != components.len()
                || flux_right.len() != components.len()
            {
                panic!("CentralUpwind spec arrays must match component count");
            }

            let (fcse_stmts, exprs) = fcse.lower_scalars(&[a_plus, a_minus], &ctx);
            body.extend(fcse_stmts);
            let (cse_stmts, exprs) = cse.eliminate(&exprs);
            body.extend(cse_stmts);
            let [a_p, a_m] = exprs
                .try_into()
                .expect("CSE returned unexpected number of expressions");
            body.push(dsl::let_expr("a_plus", a_p));
            body.push(dsl::let_expr("a_minus", a_m));
            body.push(dsl::let_expr(
                "denom",
                dsl::max(Expr::ident("a_plus") - Expr::ident("a_minus"), 1e-6),
            ));

            for (i, comp_name) in components.iter().enumerate() {
                let coupled_rank = flux_layout
                    .offset_for(comp_name)
                    .unwrap_or_else(|| panic!("missing flux layout component '{comp_name}'"));
                let Some(storage_rank) =
                    face_channels.storage_rank_for_coupled(coupled_rank)
                else {
                    continue;
                };
                let (fcse_stmts, exprs) = fcse.lower_scalars(
                    &[&u_left[i], &u_right[i], &flux_left[i], &flux_right[i]],
                    &ctx,
                );
                body.extend(fcse_stmts);
                let (cse_stmts, exprs) = cse.eliminate(&exprs);
                body.extend(cse_stmts);
                let [u_l, u_r, f_l, f_r] = exprs
                    .try_into()
                    .expect("CSE returned unexpected number of expressions");

                let num = Expr::ident("a_plus") * f_l - Expr::ident("a_minus") * f_r
                    + (Expr::ident("a_plus") * Expr::ident("a_minus")) * (u_r - u_l);
                let flux = num / Expr::ident("denom");

                body.push(dsl::assign_expr(
                    flux_face(storage_rank),
                    flux * Expr::ident("area"),
                ));
            }
        }
    }

    body
}

fn face_stmts_runtime_scheme(
    resolver: &dyn OffsetResolver,
    flux_layout: &FluxLayout,
    face_channels: &ExplicitFaceChannelLiveness,
    flux_stride: u32,
    primitives: &HashMap<&str, &Expr>,
    variants: &[(Scheme, FluxModuleKernelSpec)],
    structured: bool,
) -> Vec<Stmt> {
    #[derive(Clone, Copy)]
    struct CentralUpwindVariant<'a> {
        components: &'a [String],
        u_left: &'a [FaceScalarExpr],
        u_right: &'a [FaceScalarExpr],
        flux_left: &'a [FaceScalarExpr],
        flux_right: &'a [FaceScalarExpr],
        a_plus: &'a FaceScalarExpr,
        a_minus: &'a FaceScalarExpr,
    }
    let flux_face = |storage_rank: u32| {
        if structured {
            dsl::array_access_linear(
                "fluxes",
                Expr::ident("sfd_face_id"),
                flux_stride,
                storage_rank,
            )
        } else {
            dsl::array_access_linear(
                "fluxes",
                Expr::ident("idx"),
                flux_stride,
                storage_rank,
            )
        }
    };

    // --- Geometry preamble (kept in sync with `face_stmts`) ---
    let mut body: Vec<Stmt> = Vec::new();
    if structured {
        body.push(dsl::var_typed_expr(
            "c_neigh_vec",
            Type::vec2_f32(),
            Some(sg::sfd_vec2("sfd_other_cx", "sfd_other_cy")),
        ));
        body.push(dsl::let_typed_expr(
            "c_neigh_cell_vec",
            Type::vec2_f32(),
            Expr::ident("c_neigh_vec"),
        ));
        body.push(dsl::if_block_expr(
            Expr::ident("is_boundary"),
            dsl::block(vec![dsl::assign_expr(
                Expr::ident("c_neigh_vec"),
                Expr::ident("face_center_vec"),
            )]),
            None,
        ));
    } else {
        body.push(dsl::let_expr(
            "c_neigh",
            dsl::array_access("cell_centers", Expr::ident("neigh_idx")),
        ));
        body.push(dsl::var_typed_expr(
            "c_neigh_vec",
            Type::vec2_f32(),
            Some(typed::VecExpr::<2>::from_xy_fields(Expr::ident("c_neigh")).expr()),
        ));
        // Periodic wrap: lift the neighbor center into the owner's frame across a seam face.
        body.push(dsl::assign_expr(
            Expr::ident("c_neigh_vec"),
            typed::VecExpr::<2>::from_expr(Expr::ident("c_neigh_vec"))
                .add(&typed::VecExpr::<2>::from_xy_fields(
                    Expr::ident("face_wrap_shift").index(Expr::ident("idx")),
                ))
                .expr(),
        ));
        body.push(dsl::let_typed_expr(
            "c_neigh_cell_vec",
            Type::vec2_f32(),
            Expr::ident("c_neigh_vec"),
        ));
        body.push(dsl::if_block_expr(
            Expr::ident("is_boundary"),
            dsl::block(vec![dsl::assign_expr(
                Expr::ident("c_neigh_vec"),
                Expr::ident("face_center_vec"),
            )]),
            None,
        ));
    }

    // Match OpenFOAM's `surfaceInterpolation::weights()` (basicFvGeometryScheme).
    let d_own = dsl::abs(
        typed::VecExpr::<2>::from_expr(Expr::ident("face_center_vec"))
            .sub(&typed::VecExpr::<2>::from_expr(Expr::ident("c_owner_vec")))
            .dot(&typed::VecExpr::<2>::from_expr(Expr::ident("normal_vec"))),
    );
    body.push(dsl::let_expr("d_own", d_own));

    let d_neigh = dsl::abs(
        typed::VecExpr::<2>::from_expr(Expr::ident("c_neigh_vec"))
            .sub(&typed::VecExpr::<2>::from_expr(Expr::ident(
                "face_center_vec",
            )))
            .dot(&typed::VecExpr::<2>::from_expr(Expr::ident("normal_vec"))),
    );
    body.push(dsl::let_expr("d_neigh", d_neigh));
    body.push(dsl::let_expr(
        "total_dist",
        Expr::ident("d_own") + Expr::ident("d_neigh"),
    ));
    body.push(dsl::var_typed_expr("lambda", Type::F32, Some(0.5.into())));
    body.push(dsl::if_block_expr(
        Expr::ident("total_dist").gt(1e-6),
        dsl::block(vec![dsl::assign_expr(
            Expr::ident("lambda"),
            Expr::ident("d_neigh") / Expr::ident("total_dist"),
        )]),
        None,
    ));
    body.push(dsl::let_expr(
        "lambda_other",
        Expr::from(1.0) - Expr::ident("lambda"),
    ));

    let d_vec = typed::VecExpr::<2>::from_expr(Expr::ident("c_neigh_vec"))
        .sub(&typed::VecExpr::<2>::from_expr(Expr::ident("c_owner_vec")))
        .expr();
    body.push(dsl::let_typed_expr("d_vec", Type::vec2_f32(), d_vec));
    body.push(dsl::let_expr(
        "dist_proj",
        dsl::abs(
            typed::VecExpr::<2>::from_expr(Expr::ident("d_vec"))
                .dot(&typed::VecExpr::<2>::from_expr(Expr::ident("normal_vec"))),
        ),
    ));
    body.push(dsl::let_expr("dist", dsl::max("dist_proj", 1e-6)));

    let mut state_keys = HashSet::new();
    for (_, spec) in variants {
        collect_state_keys_from_flux_spec(spec, primitives, resolver, &mut state_keys);
    }
    let (state_vars, state_var_stmts) =
        precompute_state_vars(resolver, flux_layout, &state_keys, structured);
    body.extend(state_var_stmts);
    let ctx = LowerCtx::new(resolver, primitives, flux_layout, state_vars, structured);
    let mut cse = CseBuilder::new("_cse_");
    let mut fcse = FaceCse::new();

    if variants.is_empty() {
        panic!("runtime scheme flux module requires at least one variant spec");
    }

    // Fast-path for runtime scheme selection with pre-integrated per-component fluxes.
    //
    // This is used by the compressible Kurganov/rhoCentralFoam-style flux lowering, which
    // computes integrated face fluxes directly and does not use the CentralUpwind KT form.
    if matches!(
        &variants[0].1,
        FluxModuleKernelSpec::ScalarPerComponent { .. }
    ) {
        #[derive(Clone, Copy)]
        struct ScalarPerComponentVariant<'a> {
            components: &'a [String],
            flux: &'a [FaceScalarExpr],
        }

        let mut by_gpu_id: Vec<Option<ScalarPerComponentVariant<'_>>> = vec![None; 9];
        for (scheme, spec) in variants {
            let FluxModuleKernelSpec::ScalarPerComponent { components, flux } = spec else {
                panic!("runtime scheme flux module requires ScalarPerComponent variants");
            };

            let idx = scheme.gpu_id() as usize;
            if idx >= by_gpu_id.len() {
                continue;
            }
            if by_gpu_id[idx].is_some() {
                panic!("duplicate ScalarPerComponent variant for scheme {scheme:?}");
            }
            by_gpu_id[idx] = Some(ScalarPerComponentVariant { components, flux });
        }

        let upwind = by_gpu_id[Scheme::Upwind.gpu_id() as usize]
            .unwrap_or_else(|| panic!("runtime scheme flux module requires an Upwind variant"));

        if upwind.components.len() != flux_layout.components.len() {
            panic!("ScalarPerComponent spec component count does not match FluxLayout");
        }
        if upwind.flux.len() != upwind.components.len() {
            panic!("ScalarPerComponent spec arrays must match component count");
        }

        // Ensure all variants share the same component list/order.
        for v in by_gpu_id.iter().flatten() {
            if v.components != upwind.components {
                panic!("ScalarPerComponent variant components must match across schemes");
            }
            if v.flux.len() != v.components.len() {
                panic!("ScalarPerComponent spec arrays must match component count");
            }
        }

        let scheme_lit =
            typed::EnumExpr::<Scheme>::from_expr(Expr::ident("constants").field("scheme"));
        let is_interior = !Expr::ident("is_boundary");
        let cond_for = |scheme: Scheme| scheme_lit.clone().eq(scheme) & is_interior.clone();

        // Declare one mutable flux var per component, initialized from the Upwind variant.
        let mut var_names: Vec<String> = Vec::with_capacity(upwind.components.len());
        for comp_name in upwind.components.iter() {
            let off = flux_layout
                .offset_for(comp_name)
                .unwrap_or_else(|| panic!("missing flux layout component '{comp_name}'"));
            var_names.push(format!("phi_{off}"));
        }

        let upwind_roots: Vec<&FaceScalarExpr> = upwind.flux.iter().collect();
        let (fcse_stmts, upwind_flux_exprs) = fcse.lower_scalars(&upwind_roots, &ctx);
        body.extend(fcse_stmts);
        let (cse_stmts, upwind_flux_exprs) = cse.eliminate(&upwind_flux_exprs);
        body.extend(cse_stmts);
        for (name, expr) in var_names.iter().zip(upwind_flux_exprs.into_iter()) {
            body.push(dsl::var_typed_expr(name, Type::F32, Some(expr)));
        }

        for scheme in [
            Scheme::SecondOrderUpwind,
            Scheme::QUICK,
            Scheme::SecondOrderUpwindMinMod,
            Scheme::SecondOrderUpwindVanLeer,
            Scheme::QUICKMinMod,
            Scheme::QUICKVanLeer,
            Scheme::Kep,
            Scheme::Slau2,
        ] {
            let Some(v) = by_gpu_id.get(scheme.gpu_id() as usize).and_then(|v| *v) else {
                continue;
            };

            let cond = cond_for(scheme);
            let scheme_roots: Vec<&FaceScalarExpr> = v.flux.iter().collect();
            let (fcse_stmts, scheme_flux_exprs) = fcse.lower_scalars(&scheme_roots, &ctx);
            let (cse_stmts, scheme_flux_exprs) = cse.eliminate(&scheme_flux_exprs);

            body.push(dsl::if_block_expr(
                cond,
                dsl::block(
                    fcse_stmts
                        .into_iter()
                        .chain(cse_stmts)
                        .chain(
                            var_names.iter().zip(scheme_flux_exprs.into_iter()).map(
                                |(name, expr)| dsl::assign_expr(Expr::ident(name.clone()), expr),
                            ),
                        )
                        .collect(),
                ),
                None,
            ));
        }

        for (name, comp_name) in var_names.iter().zip(upwind.components.iter()) {
            let coupled_rank = flux_layout
                .offset_for(comp_name)
                .unwrap_or_else(|| panic!("missing flux layout component '{comp_name}'"));
            let Some(storage_rank) =
                face_channels.storage_rank_for_coupled(coupled_rank)
            else {
                continue;
            };
            body.push(dsl::assign_expr(
                flux_face(storage_rank),
                Expr::ident(name.clone()),
            ));
        }

        return body;
    }

    let mut by_gpu_id: Vec<Option<CentralUpwindVariant<'_>>> = vec![None; 9];
    for (scheme, spec) in variants {
        let FluxModuleKernelSpec::CentralUpwind {
            components,
            u_left,
            u_right,
            flux_left,
            flux_right,
            a_plus,
            a_minus,
            ..
        } = spec
        else {
            panic!("runtime scheme flux module requires CentralUpwind variants");
        };

        let idx = scheme.gpu_id() as usize;
        if idx >= by_gpu_id.len() {
            continue;
        }
        if by_gpu_id[idx].is_some() {
            panic!("duplicate CentralUpwind variant for scheme {scheme:?}");
        }
        by_gpu_id[idx] = Some(CentralUpwindVariant {
            components,
            u_left,
            u_right,
            flux_left,
            flux_right,
            a_plus,
            a_minus,
        });
    }

    let upwind = by_gpu_id[Scheme::Upwind.gpu_id() as usize]
        .unwrap_or_else(|| panic!("runtime scheme flux module requires an Upwind variant"));

    if upwind.components.len() != flux_layout.components.len() {
        panic!("CentralUpwind spec component count does not match FluxLayout");
    }
    if upwind.u_left.len() != upwind.components.len()
        || upwind.u_right.len() != upwind.components.len()
        || upwind.flux_left.len() != upwind.components.len()
        || upwind.flux_right.len() != upwind.components.len()
    {
        panic!("CentralUpwind spec arrays must match component count");
    }

    // Ensure all variants share the same component list/order.
    for v in by_gpu_id.iter().flatten() {
        if v.components != upwind.components {
            panic!("CentralUpwind variant components must match across schemes");
        }
    }

    let scheme_lit = typed::EnumExpr::<Scheme>::from_expr(Expr::ident("constants").field("scheme"));
    let is_interior = !Expr::ident("is_boundary");
    let cond_for = |scheme: Scheme| scheme_lit.clone().eq(scheme) & is_interior.clone();

    let (fcse_stmts, exprs) = fcse.lower_scalars(&[upwind.a_plus, upwind.a_minus], &ctx);
    body.extend(fcse_stmts);
    let (cse_stmts, exprs) = cse.eliminate(&exprs);
    body.extend(cse_stmts);
    let [a_plus_upwind, a_minus_upwind] = exprs
        .try_into()
        .expect("CSE returned unexpected number of expressions");
    body.push(dsl::var_typed_expr(
        "a_plus",
        Type::F32,
        Some(a_plus_upwind),
    ));
    body.push(dsl::var_typed_expr(
        "a_minus",
        Type::F32,
        Some(a_minus_upwind),
    ));

    for scheme in [
        Scheme::SecondOrderUpwind,
        Scheme::QUICK,
        Scheme::SecondOrderUpwindMinMod,
        Scheme::SecondOrderUpwindVanLeer,
        Scheme::QUICKMinMod,
        Scheme::QUICKVanLeer,
        Scheme::Kep,
        Scheme::Slau2,
    ] {
        let Some(v) = by_gpu_id.get(scheme.gpu_id() as usize).and_then(|v| *v) else {
            continue;
        };

        let cond = cond_for(scheme);
        let (fcse_stmts, exprs) = fcse.lower_scalars(&[v.a_plus, v.a_minus], &ctx);
        let (cse_stmts, exprs) = cse.eliminate(&exprs);
        let [a_p, a_m] = exprs
            .try_into()
            .expect("CSE returned unexpected number of expressions");

        body.push(dsl::if_block_expr(
            cond,
            dsl::block(
                fcse_stmts
                    .into_iter()
                    .chain(cse_stmts)
                    .chain([
                        dsl::assign_expr(Expr::ident("a_plus"), a_p),
                        dsl::assign_expr(Expr::ident("a_minus"), a_m),
                    ])
                    .collect(),
            ),
            None,
        ));
    }

    body.push(dsl::let_expr(
        "denom",
        dsl::max(Expr::ident("a_plus") - Expr::ident("a_minus"), 1e-6),
    ));

    for (i, comp_name) in upwind.components.iter().enumerate() {
        let off = flux_layout
            .offset_for(comp_name)
            .unwrap_or_else(|| panic!("missing flux layout component '{comp_name}'"));

        let u_l = format!("u_l_{off}");
        let u_r = format!("u_r_{off}");
        let f_l = format!("f_l_{off}");
        let f_r = format!("f_r_{off}");

        let (fcse_stmts, exprs) = fcse.lower_scalars(
            &[
                &upwind.u_left[i],
                &upwind.u_right[i],
                &upwind.flux_left[i],
                &upwind.flux_right[i],
            ],
            &ctx,
        );
        body.extend(fcse_stmts);
        let (cse_stmts, exprs) = cse.eliminate(&exprs);
        body.extend(cse_stmts);
        let [u_l_upwind, u_r_upwind, f_l_upwind, f_r_upwind] = exprs
            .try_into()
            .expect("CSE returned unexpected number of expressions");

        body.push(dsl::var_typed_expr(&u_l, Type::F32, Some(u_l_upwind)));
        body.push(dsl::var_typed_expr(&u_r, Type::F32, Some(u_r_upwind)));
        body.push(dsl::var_typed_expr(&f_l, Type::F32, Some(f_l_upwind)));
        body.push(dsl::var_typed_expr(&f_r, Type::F32, Some(f_r_upwind)));

        for scheme in [
            Scheme::SecondOrderUpwind,
            Scheme::QUICK,
            Scheme::SecondOrderUpwindMinMod,
            Scheme::SecondOrderUpwindVanLeer,
            Scheme::QUICKMinMod,
            Scheme::QUICKVanLeer,
            Scheme::Kep,
            Scheme::Slau2,
        ] {
            let Some(v) = by_gpu_id.get(scheme.gpu_id() as usize).and_then(|v| *v) else {
                continue;
            };

            let cond = cond_for(scheme);
            let (fcse_stmts, exprs) = fcse.lower_scalars(
                &[
                    &v.u_left[i],
                    &v.u_right[i],
                    &v.flux_left[i],
                    &v.flux_right[i],
                ],
                &ctx,
            );
            let (cse_stmts, exprs) = cse.eliminate(&exprs);
            let [u_l_expr, u_r_expr, f_l_expr, f_r_expr] = exprs
                .try_into()
                .expect("CSE returned unexpected number of expressions");

            body.push(dsl::if_block_expr(
                cond,
                dsl::block(
                    fcse_stmts
                        .into_iter()
                        .chain(cse_stmts)
                        .chain([
                            dsl::assign_expr(Expr::ident(&u_l), u_l_expr),
                            dsl::assign_expr(Expr::ident(&u_r), u_r_expr),
                            dsl::assign_expr(Expr::ident(&f_l), f_l_expr),
                            dsl::assign_expr(Expr::ident(&f_r), f_r_expr),
                        ])
                        .collect(),
                ),
                None,
            ));
        }

        let num = Expr::ident("a_plus") * Expr::ident(&f_l)
            - Expr::ident("a_minus") * Expr::ident(&f_r)
            + (Expr::ident("a_plus") * Expr::ident("a_minus"))
                * (Expr::ident(&u_r) - Expr::ident(&u_l));
        let flux = num / Expr::ident("denom");

        if let Some(storage_rank) = face_channels.storage_rank_for_coupled(off) {
            body.push(dsl::assign_expr(
                // Use the face-id-aware helper: in the structured lowering the flux slot
                // is `sfd_face_id`, not the cell `idx` (same class of bug as the boundary
                // BC-table keying above).
                flux_face(storage_rank),
                flux * Expr::ident("area"),
            ));
        }
    }

    body
}

#[derive(Debug, Clone, Copy, PartialEq, Eq, Hash)]
struct StateKey<'a> {
    side: FaceSide,
    field: &'a str,
    component: u32,
}

fn sanitize_ident(raw: &str) -> String {
    let mut out: String = raw
        .chars()
        .map(|c| {
            if c.is_ascii_alphanumeric() || c == '_' {
                c
            } else {
                '_'
            }
        })
        .collect();
    if out.chars().next().is_some_and(|c| c.is_ascii_digit()) {
        out.insert(0, '_');
    }
    out
}

fn state_var_name(resolver: &dyn OffsetResolver, key: StateKey<'_>) -> String {
    let side = match key.side {
        FaceSide::Owner => "own",
        FaceSide::Neighbor => "neigh",
    };

    let mut name = format!("s_{side}_{}", sanitize_ident(key.field));

    let suffix = resolver.field_kind(key.field);
    match suffix {
        Some(FieldKind::Vector2) => {
            if key.component > 1 {
                return format!("{name}_c{}", key.component);
            }
            name.push('_');
            name.push_str(XY::from_index(key.component).suffix());
        }
        Some(FieldKind::Vector3) => {
            name.push_str(match key.component {
                0 => "_x",
                1 => "_y",
                2 => "_z",
                _ => return format!("{name}_c{}", key.component),
            });
        }
        _ => {
            if key.component != 0 {
                name.push_str(&format!("_c{}", key.component));
            }
        }
    }

    name
}

fn collect_state_keys_from_flux_spec<'a>(
    spec: &'a FluxModuleKernelSpec,
    primitives: &'a HashMap<&'a str, &'a Expr>,
    resolver: &dyn OffsetResolver,
    out: &mut HashSet<StateKey<'a>>,
) {
    match spec {
        FluxModuleKernelSpec::ScalarReplicated { phi } => {
            collect_state_keys_from_scalar(phi, primitives, resolver, out);
        }
        FluxModuleKernelSpec::ScalarPerComponent { flux, .. } => {
            for expr in flux {
                collect_state_keys_from_scalar(expr, primitives, resolver, out);
            }
        }
        FluxModuleKernelSpec::CentralUpwind {
            u_left,
            u_right,
            flux_left,
            flux_right,
            a_plus,
            a_minus,
            ..
        } => {
            for expr in u_left {
                collect_state_keys_from_scalar(expr, primitives, resolver, out);
            }
            for expr in u_right {
                collect_state_keys_from_scalar(expr, primitives, resolver, out);
            }
            for expr in flux_left {
                collect_state_keys_from_scalar(expr, primitives, resolver, out);
            }
            for expr in flux_right {
                collect_state_keys_from_scalar(expr, primitives, resolver, out);
            }
            collect_state_keys_from_scalar(a_plus, primitives, resolver, out);
            collect_state_keys_from_scalar(a_minus, primitives, resolver, out);
        }
    }
}

fn collect_state_keys_from_vec2<'a>(
    expr: &'a FaceVec2Expr,
    primitives: &'a HashMap<&'a str, &'a Expr>,
    resolver: &dyn OffsetResolver,
    out: &mut HashSet<StateKey<'a>>,
) {
    match expr {
        FaceVec2Expr::Builtin(_) => {}
        FaceVec2Expr::CellStateVec2 { .. } => {}
        FaceVec2Expr::Vec2(x, y) => {
            collect_state_keys_from_scalar(x, primitives, resolver, out);
            collect_state_keys_from_scalar(y, primitives, resolver, out);
        }
        FaceVec2Expr::StateVec2 { side, field } => {
            // `FaceVec2Expr` is always `vec2`, so we only materialize x/y.
            for axis in XY::ALL {
                out.insert(StateKey {
                    side: *side,
                    field: field.as_str(),
                    component: axis.to_usize() as u32,
                });
            }
        }
        FaceVec2Expr::Add(a, b) | FaceVec2Expr::Sub(a, b) | FaceVec2Expr::Lerp(a, b) => {
            collect_state_keys_from_vec2(a, primitives, resolver, out);
            collect_state_keys_from_vec2(b, primitives, resolver, out);
        }
        FaceVec2Expr::Neg(a) => collect_state_keys_from_vec2(a, primitives, resolver, out),
        FaceVec2Expr::MulScalar(v, s) => {
            collect_state_keys_from_vec2(v, primitives, resolver, out);
            collect_state_keys_from_scalar(s, primitives, resolver, out);
        }
    }
}

fn collect_state_keys_from_primitive_expr<'a>(
    expr: &'a Expr,
    side: FaceSide,
    resolver: &dyn OffsetResolver,
    out: &mut HashSet<StateKey<'a>>,
) {
    use cfd2_ir::ast::ExprNode;
    match expr.node() {
        ExprNode::Literal(_) => {}
        ExprNode::Ident(name) => {
            let (base, component) = resolve_state_field_component_resolver(resolver, name);
            out.insert(StateKey {
                side,
                field: base,
                component,
            });
        }
        ExprNode::Binary { left, right, .. } => {
            collect_state_keys_from_primitive_expr(left, side, resolver, out);
            collect_state_keys_from_primitive_expr(right, side, resolver, out);
        }
        ExprNode::Unary { expr: inner, .. } => {
            collect_state_keys_from_primitive_expr(inner, side, resolver, out);
        }
        ExprNode::Call { args, .. } => {
            for arg in args {
                collect_state_keys_from_primitive_expr(arg, side, resolver, out);
            }
        }
        ExprNode::Field { base, .. } => {
            collect_state_keys_from_primitive_expr(base, side, resolver, out);
        }
        ExprNode::Index { base, index } => {
            collect_state_keys_from_primitive_expr(base, side, resolver, out);
            collect_state_keys_from_primitive_expr(index, side, resolver, out);
        }
    }
}

fn collect_state_keys_from_scalar<'a>(
    expr: &'a FaceScalarExpr,
    primitives: &'a HashMap<&'a str, &'a Expr>,
    resolver: &dyn OffsetResolver,
    out: &mut HashSet<StateKey<'a>>,
) {
    match expr {
        FaceScalarExpr::Literal(_)
        | FaceScalarExpr::Builtin(_)
        | FaceScalarExpr::Constant { .. }
        | FaceScalarExpr::LowMachParam(_)
        | FaceScalarExpr::BoundaryDirichlet { .. }
        | FaceScalarExpr::MeshFlux => {}
        FaceScalarExpr::State { side, name } => {
            out.insert(StateKey {
                side: *side,
                field: name.as_str(),
                component: 0,
            });
        }
        // Raw cell reads deliberately bypass the BC-applied state precompute.
        FaceScalarExpr::CellState { .. } => {}
        FaceScalarExpr::Primitive { side, name } => {
            let prim = primitives.get(name.as_str()).unwrap_or_else(|| {
                panic!("primitive '{}' not found in PrimitiveDerivations", name)
            });
            collect_state_keys_from_primitive_expr(prim, *side, resolver, out);
        }
        FaceScalarExpr::Add(a, b)
        | FaceScalarExpr::Sub(a, b)
        | FaceScalarExpr::Mul(a, b)
        | FaceScalarExpr::Div(a, b)
        | FaceScalarExpr::Max(a, b)
        | FaceScalarExpr::Min(a, b)
        | FaceScalarExpr::Lerp(a, b) => {
            collect_state_keys_from_scalar(a, primitives, resolver, out);
            collect_state_keys_from_scalar(b, primitives, resolver, out);
        }
        FaceScalarExpr::Neg(a) | FaceScalarExpr::Abs(a) | FaceScalarExpr::Sqrt(a) => {
            collect_state_keys_from_scalar(a, primitives, resolver, out);
        }
        FaceScalarExpr::Dot(a, b) => {
            collect_state_keys_from_vec2(a, primitives, resolver, out);
            collect_state_keys_from_vec2(b, primitives, resolver, out);
        }
    }
}

fn precompute_state_vars<'a>(
    resolver: &dyn OffsetResolver,
    flux_layout: &FluxLayout,
    keys: &HashSet<StateKey<'a>>,
    structured: bool,
) -> (HashMap<StateKey<'a>, String>, Vec<Stmt>) {
    let mut vars = HashMap::new();
    let mut stmts = Vec::new();

    let mut ordered: Vec<StateKey<'a>> = keys.iter().copied().collect();
    ordered.sort_by(|a, b| {
        let side_rank = |s: FaceSide| if s == FaceSide::Owner { 0 } else { 1 };
        side_rank(a.side)
            .cmp(&side_rank(b.side))
            .then_with(|| a.field.cmp(b.field))
            .then_with(|| a.component.cmp(&b.component))
    });

    for key in ordered {
        let name = state_var_name(resolver, key);
        let expr = state_component_at_side_resolver(
            resolver,
            "state",
            key.side,
            key.field,
            key.component,
            flux_layout,
            structured,
        );
        stmts.push(dsl::let_expr(&name, expr));
        vars.insert(key, name);
    }

    (vars, stmts)
}

// ── Hash-consed FaceScalarExpr lowering ─────────────────────────────────
//
// `derive_central_upwind` builds each scheme variant's `FaceScalarExpr`
// trees by deep-cloning shared subexpressions (reconstruction, EOS and
// wave-speed subtrees) at every reference, so the input trees carry massive
// structural duplication (~200k nodes per variant for the compressible
// model, ~1.5M lowered nodes across the 7 runtime-scheme variants) even
// though the deduplicated WGSL output is ~111 KB. Lowering naively
// materializes every duplicate copy into `Expr` allocations only for
// `CseBuilder::eliminate` to hash the huge tree and collapse it back
// (~6 s per compressible CPU solver construction; ~24 s of every fresh
// build via build.rs).
//
// Fix: dedupe DURING lowering. Per eliminate scope (exactly the region
// where that call's `_cse_*` prelude statements land), precompute a
// bottom-up structural hash plus an occurrence count over the deduplicated
// dag, then lower with a memo: a subtree that occurs >= FCSE_MIN_COUNT
// times and weighs >= FCSE_MIN_WEIGHT nodes is materialized ONCE as
// `let _fcse_N = <lowered>;` into a statement sink, and every later
// occurrence lowers to `Expr::ident("_fcse_N")`. Hoisting a pure
// subexpression into a `let` in the same block is IEEE-neutral (same ops,
// same evaluation order), and the sink is emitted exactly where the
// corresponding `cse.eliminate` statements go, so placement semantics are
// unchanged. The downstream `CseBuilder` still runs and catches duplicates
// that only arise between the lowered roots.

/// Minimum occurrences for a subtree to be memoized/hoisted.
const FCSE_MIN_COUNT: u32 = 2;
/// Minimum subtree weight (see `scan_scalar`) for hoisting into a `let` —
/// avoids churning the output on leaves and near-leaves.
const FCSE_MIN_WEIGHT: u32 = 4;
/// Weight stand-in for a `Primitive` leaf: a single IR node that expands to
/// the primitive's full EOS expression during lowering, so a repeated
/// primitive read is always worth hoisting.
const FCSE_PRIMITIVE_WEIGHT: u32 = FCSE_MIN_WEIGHT;

/// splitmix64-style hash combine; deterministic across runs and platforms.
#[inline]
fn fcse_mix(h: u64, v: u64) -> u64 {
    let mut x = h
        .wrapping_mul(0x9E37_79B9_7F4A_7C15)
        .wrapping_add(v)
        .wrapping_add(0x2545_F491_4F6C_DD1D);
    x = (x ^ (x >> 30)).wrapping_mul(0xBF58_476D_1CE4_E5B9);
    x = (x ^ (x >> 27)).wrapping_mul(0x94D0_49BB_1331_11EB);
    x ^ (x >> 31)
}

/// FNV-1a 64 of a string, folded into `tag`.
#[inline]
fn fcse_str(tag: u64, s: &str) -> u64 {
    let mut h: u64 = 0xcbf2_9ce4_8422_2325;
    for &b in s.as_bytes() {
        h ^= b as u64;
        h = h.wrapping_mul(0x0000_0100_0000_01b3);
    }
    fcse_mix(tag, h)
}

#[inline]
fn fcse_side(side: FaceSide) -> u64 {
    match side {
        FaceSide::Owner => 0,
        FaceSide::Neighbor => 1,
    }
}

/// Shared `_fcse_*` name allocator for one kernel body. Sibling scopes emit
/// `let`s into the same WGSL block, so ids must be monotonic across scopes
/// (mirrors how one `CseBuilder` is reused for all `_cse_*` names).
struct FaceCse {
    next_id: u32,
}

impl FaceCse {
    fn new() -> Self {
        Self { next_id: 0 }
    }

    /// Lower `roots` with hash-consed deduplication. Returns the hoisted
    /// `let _fcse_N = ...;` prelude (dependency-ordered) and the rewritten
    /// roots. The prelude must be emitted into the exact block that receives
    /// the downstream `cse.eliminate` statements for these roots.
    fn lower_scalars<'a>(
        &mut self,
        roots: &[&'a FaceScalarExpr],
        ctx: &LowerCtx<'a>,
    ) -> (Vec<Stmt>, Vec<Expr>) {
        let mut scope = FaceCseScope::enabled(self.next_id);
        for root in roots {
            scope.scan_scalar(root);
        }
        for root in roots {
            scope.count_scalar(root);
        }
        let exprs: Vec<Expr> = roots
            .iter()
            .map(|root| lower_scalar(root, ctx, &mut scope))
            .collect();
        self.next_id = scope.next_id;
        // Expr-level simplifications (e.g. dot with a unit basis vector) can
        // drop a lowered subtree after it was hoisted; prune `let`s nothing
        // references so the kernel never evaluates dead code.
        let stmts = prune_unused_lets(scope.sink, &exprs);
        (stmts, exprs)
    }
}

/// One hash-consing scope (see [`FaceCse::lower_scalars`]).
struct FaceCseScope<'a> {
    enabled: bool,
    /// Node address -> (structural hash, weight). The trees are `Box`-based,
    /// so every duplicate copy has its own address; the scan pass fills this
    /// for every node reachable from the scope's roots.
    scalar_info: HashMap<usize, (u64, u32)>,
    vec2_info: HashMap<usize, (u64, u32)>,
    /// Structural hash -> occurrences. Counting recurses into a scalar
    /// subtree only on its FIRST occurrence: later copies lower to a memo
    /// hit, so their children are never materialized again. vec2 nodes are
    /// not memoized (their lowering re-derives the small component skeleton
    /// per copy), so counting always recurses through them.
    counts: HashMap<u64, u32>,
    /// Structural hash -> (lowered form, representative subtree). Heavy
    /// subtrees map to `Expr::ident("_fcse_N")` of their hoisted `let`;
    /// light duplicates map to the (Arc-shared) lowered expression itself so
    /// re-lowering is skipped without changing the emitted text. The
    /// representative is compared structurally on every lookup, so a 64-bit
    /// hash collision can only cost a missed dedup, never a wrong rewrite.
    memo: HashMap<u64, (Expr, &'a FaceScalarExpr)>,
    /// Hoisted `let _fcse_N = ...;` statements (dependency-ordered).
    sink: Vec<Stmt>,
    next_id: u32,
}

impl<'a> FaceCseScope<'a> {
    fn enabled(next_id: u32) -> Self {
        Self {
            enabled: true,
            scalar_info: HashMap::new(),
            vec2_info: HashMap::new(),
            counts: HashMap::new(),
            memo: HashMap::new(),
            sink: Vec::new(),
            next_id,
        }
    }

    /// Inert scope for lowerings without a hash-consing region (call sites
    /// that never ran `cse.eliminate` either); lowering behaves exactly as
    /// it did before the memo existed.
    fn disabled() -> Self {
        Self {
            enabled: false,
            ..Self::enabled(0)
        }
    }

    // ── scan: bottom-up structural hash + subtree weight per node copy ──

    fn scan_scalar(&mut self, e: &'a FaceScalarExpr) -> (u64, u32) {
        let key = e as *const FaceScalarExpr as usize;
        if let Some(&info) = self.scalar_info.get(&key) {
            return info;
        }
        use FaceScalarExpr as S;
        let info = match e {
            S::Literal(v) => (fcse_mix(1, u64::from(v.to_bits())), 1),
            S::Builtin(b) => (fcse_mix(2, *b as u64), 1),
            S::Constant { name } => (fcse_str(3, name), 1),
            S::LowMachParam(p) => (fcse_mix(4, *p as u64), 1),
            S::State { side, name } => (fcse_mix(fcse_side(*side), fcse_str(5, name)), 1),
            S::CellState { side, name } => {
                (fcse_mix(fcse_side(*side), fcse_str(19, name)), 1)
            }
            S::BoundaryDirichlet { name } => (fcse_str(20, name), 1),
            S::Primitive { side, name } => (
                fcse_mix(fcse_side(*side), fcse_str(6, name)),
                FCSE_PRIMITIVE_WEIGHT,
            ),
            S::MeshFlux => (fcse_mix(7, 7), 1),
            S::Add(a, b) => self.scan_scalar2(8, a, b),
            S::Sub(a, b) => self.scan_scalar2(9, a, b),
            S::Mul(a, b) => self.scan_scalar2(10, a, b),
            S::Div(a, b) => self.scan_scalar2(11, a, b),
            S::Max(a, b) => self.scan_scalar2(12, a, b),
            S::Min(a, b) => self.scan_scalar2(13, a, b),
            S::Lerp(a, b) => self.scan_scalar2(14, a, b),
            S::Neg(a) => self.scan_scalar1(15, a),
            S::Abs(a) => self.scan_scalar1(16, a),
            S::Sqrt(a) => self.scan_scalar1(17, a),
            S::Dot(a, b) => {
                let (ha, wa) = self.scan_vec2(a);
                let (hb, wb) = self.scan_vec2(b);
                (
                    fcse_mix(fcse_mix(18, ha), hb),
                    1u32.saturating_add(wa).saturating_add(wb),
                )
            }
        };
        self.scalar_info.insert(key, info);
        info
    }

    fn scan_scalar1(&mut self, tag: u64, a: &'a FaceScalarExpr) -> (u64, u32) {
        let (ha, wa) = self.scan_scalar(a);
        (fcse_mix(tag, ha), 1u32.saturating_add(wa))
    }

    fn scan_scalar2(
        &mut self,
        tag: u64,
        a: &'a FaceScalarExpr,
        b: &'a FaceScalarExpr,
    ) -> (u64, u32) {
        let (ha, wa) = self.scan_scalar(a);
        let (hb, wb) = self.scan_scalar(b);
        (
            fcse_mix(fcse_mix(tag, ha), hb),
            1u32.saturating_add(wa).saturating_add(wb),
        )
    }

    fn scan_vec2(&mut self, e: &'a FaceVec2Expr) -> (u64, u32) {
        let key = e as *const FaceVec2Expr as usize;
        if let Some(&info) = self.vec2_info.get(&key) {
            return info;
        }
        use FaceVec2Expr as V;
        let info = match e {
            V::Builtin(FaceVec2Builtin::Normal) => (fcse_mix(32, 0), 1),
            V::Builtin(FaceVec2Builtin::CellToFace { side }) => {
                (fcse_mix(32, 1 + fcse_side(*side)), 1)
            }
            V::Vec2(x, y) => {
                let (hx, wx) = self.scan_scalar(x);
                let (hy, wy) = self.scan_scalar(y);
                (
                    fcse_mix(fcse_mix(33, hx), hy),
                    1u32.saturating_add(wx).saturating_add(wy),
                )
            }
            V::StateVec2 { side, field } => (fcse_mix(fcse_side(*side), fcse_str(34, field)), 1),
            V::CellStateVec2 { side, field } => {
                (fcse_mix(fcse_side(*side), fcse_str(35, field)), 1)
            }
            V::Add(a, b) => self.scan_vec2_2(36, a, b),
            V::Sub(a, b) => self.scan_vec2_2(37, a, b),
            V::Lerp(a, b) => self.scan_vec2_2(38, a, b),
            V::Neg(a) => {
                let (ha, wa) = self.scan_vec2(a);
                (fcse_mix(39, ha), 1u32.saturating_add(wa))
            }
            V::MulScalar(v, s) => {
                let (hv, wv) = self.scan_vec2(v);
                let (hs, ws) = self.scan_scalar(s);
                (
                    fcse_mix(fcse_mix(40, hv), hs),
                    1u32.saturating_add(wv).saturating_add(ws),
                )
            }
        };
        self.vec2_info.insert(key, info);
        info
    }

    fn scan_vec2_2(&mut self, tag: u64, a: &'a FaceVec2Expr, b: &'a FaceVec2Expr) -> (u64, u32) {
        let (ha, wa) = self.scan_vec2(a);
        let (hb, wb) = self.scan_vec2(b);
        (
            fcse_mix(fcse_mix(tag, ha), hb),
            1u32.saturating_add(wa).saturating_add(wb),
        )
    }

    // ── count: occurrences over the deduplicated dag ──

    fn count_scalar(&mut self, e: &'a FaceScalarExpr) {
        let key = e as *const FaceScalarExpr as usize;
        let (h, _) = self.scalar_info[&key];
        let c = self.counts.entry(h).or_insert(0);
        *c += 1;
        if *c > 1 {
            // Later occurrences lower to a memo hit; their children are
            // never materialized again, so don't inflate the child counts.
            return;
        }
        use FaceScalarExpr as S;
        match e {
            S::Literal(_)
            | S::Builtin(_)
            | S::Constant { .. }
            | S::LowMachParam(_)
            | S::State { .. }
            | S::CellState { .. }
            | S::BoundaryDirichlet { .. }
            | S::Primitive { .. }
            | S::MeshFlux => {}
            S::Add(a, b)
            | S::Sub(a, b)
            | S::Mul(a, b)
            | S::Div(a, b)
            | S::Max(a, b)
            | S::Min(a, b)
            | S::Lerp(a, b) => {
                self.count_scalar(a);
                self.count_scalar(b);
            }
            S::Neg(a) | S::Abs(a) | S::Sqrt(a) => self.count_scalar(a),
            S::Dot(a, b) => {
                self.count_vec2(a);
                self.count_vec2(b);
            }
        }
    }

    /// vec2 nodes are never memoized, so every copy's scalar children WILL
    /// be lowered once per copy — always recurse so those children are
    /// counted per copy.
    fn count_vec2(&mut self, e: &'a FaceVec2Expr) {
        use FaceVec2Expr as V;
        match e {
            V::Builtin(_) | V::StateVec2 { .. } | V::CellStateVec2 { .. } => {}
            V::Vec2(x, y) => {
                self.count_scalar(x);
                self.count_scalar(y);
            }
            V::Add(a, b) | V::Sub(a, b) | V::Lerp(a, b) => {
                self.count_vec2(a);
                self.count_vec2(b);
            }
            V::Neg(a) => self.count_vec2(a),
            V::MulScalar(v, s) => {
                self.count_vec2(v);
                self.count_scalar(s);
            }
        }
    }

    // ── memo ──

    /// If `e` was already lowered in this scope, return its shared form.
    fn memo_hit(&self, e: &'a FaceScalarExpr) -> Option<Expr> {
        if !self.enabled {
            return None;
        }
        let key = e as *const FaceScalarExpr as usize;
        let &(h, _) = self.scalar_info.get(&key)?;
        let (cached, rep) = self.memo.get(&h)?;
        // Structural verification: a hash collision must never alias two
        // different subtrees (worst case we just miss the dedup).
        if *rep == e {
            Some(cached.clone())
        } else {
            None
        }
    }

    /// Record the lowering of a duplicated subtree: hoist heavy ones into a
    /// `let _fcse_N` in the sink, cache light ones as-is (Arc-shared).
    fn maybe_hoist(&mut self, e: &'a FaceScalarExpr, lowered: Expr) -> Expr {
        if !self.enabled {
            return lowered;
        }
        let key = e as *const FaceScalarExpr as usize;
        let Some(&(h, w)) = self.scalar_info.get(&key) else {
            return lowered;
        };
        if self.counts.get(&h).copied().unwrap_or(0) < FCSE_MIN_COUNT
            || self.memo.contains_key(&h)
        {
            return lowered;
        }
        use cfd2_ir::ast::ExprNode;
        let trivial = matches!(lowered.node(), ExprNode::Ident(_) | ExprNode::Literal(_));
        if w < FCSE_MIN_WEIGHT || trivial {
            // Duplicated but not worth a `let`: cache the lowered form so
            // later occurrences skip re-lowering (emitted text unchanged).
            self.memo.insert(h, (lowered.clone(), e));
            return lowered;
        }
        let name = format!("_fcse_{}", self.next_id);
        self.next_id += 1;
        self.sink.push(Stmt::Let {
            name: name.clone(),
            ty: None,
            expr: lowered,
        });
        let ident = Expr::ident(name);
        self.memo.insert(h, (ident.clone(), e));
        ident
    }
}

/// Drop hoisted `let`s that ended up unreferenced (an Expr-level
/// simplification can discard a subtree after it was hoisted).
fn prune_unused_lets(sink: Vec<Stmt>, roots: &[Expr]) -> Vec<Stmt> {
    fn collect_idents(expr: &Expr, out: &mut HashSet<String>) {
        use cfd2_ir::ast::ExprNode;
        match expr.node() {
            ExprNode::Literal(_) => {}
            ExprNode::Ident(name) => {
                out.insert(name.clone());
            }
            ExprNode::Field { base, .. } => collect_idents(base, out),
            ExprNode::Index { base, index } => {
                collect_idents(base, out);
                collect_idents(index, out);
            }
            ExprNode::Unary { expr: inner, .. } => collect_idents(inner, out),
            ExprNode::Binary { left, right, .. } => {
                collect_idents(left, out);
                collect_idents(right, out);
            }
            ExprNode::Call { callee, args } => {
                collect_idents(callee, out);
                for arg in args {
                    collect_idents(arg, out);
                }
            }
        }
    }

    let mut used = HashSet::new();
    for root in roots {
        collect_idents(root, &mut used);
    }
    let mut kept: Vec<Stmt> = Vec::with_capacity(sink.len());
    for stmt in sink.into_iter().rev() {
        let keep = match &stmt {
            Stmt::Let { name, expr, .. } => {
                if used.contains(name) {
                    collect_idents(expr, &mut used);
                    true
                } else {
                    false
                }
            }
            _ => true,
        };
        if keep {
            kept.push(stmt);
        }
    }
    kept.reverse();
    kept
}

struct LowerCtx<'a> {
    resolver: &'a dyn OffsetResolver,
    primitives: &'a HashMap<&'a str, &'a Expr>,
    flux_layout: &'a FluxLayout,
    state_vars: HashMap<StateKey<'a>, String>,
    structured: bool,
}

impl<'a> LowerCtx<'a> {
    fn new(
        resolver: &'a dyn OffsetResolver,
        primitives: &'a HashMap<&'a str, &'a Expr>,
        flux_layout: &'a FluxLayout,
        state_vars: HashMap<StateKey<'a>, String>,
        structured: bool,
    ) -> Self {
        Self {
            resolver,
            primitives,
            flux_layout,
            state_vars,
            structured,
        }
    }

    fn state_scalar(&self, side: FaceSide, field: &'a str, component: u32) -> Expr {
        let key = StateKey {
            side,
            field,
            component,
        };
        if let Some(name) = self.state_vars.get(&key) {
            return Expr::ident(name.clone());
        }
        state_component_at_side_resolver(
            self.resolver,
            "state",
            side,
            field,
            component,
            self.flux_layout,
            self.structured,
        )
    }
}

fn lower_vec2<'a>(
    expr: &'a FaceVec2Expr,
    ctx: &LowerCtx<'a>,
    cse: &mut FaceCseScope<'a>,
) -> typed::VecExpr<2> {
    match expr {
        FaceVec2Expr::Builtin(FaceVec2Builtin::Normal) => {
            typed::VecExpr::<2>::from_expr(Expr::ident("normal_vec"))
        }
        FaceVec2Expr::Builtin(FaceVec2Builtin::CellToFace { side }) => {
            let face = typed::VecExpr::<2>::from_expr(Expr::ident("face_center_vec"));
            let center = match side {
                FaceSide::Owner => typed::VecExpr::<2>::from_expr(Expr::ident("c_owner_vec")),
                FaceSide::Neighbor => {
                    typed::VecExpr::<2>::from_expr(Expr::ident("c_neigh_cell_vec"))
                }
            };
            face.sub(&center)
        }
        FaceVec2Expr::Vec2(x, y) => typed::VecExpr::<2>::from_components([
            lower_scalar(x, ctx, cse),
            lower_scalar(y, ctx, cse),
        ]),
        FaceVec2Expr::StateVec2 { side, field } => {
            let x = ctx.state_scalar(*side, field.as_str(), XY::X.to_usize() as u32);
            let y = ctx.state_scalar(*side, field.as_str(), XY::Y.to_usize() as u32);

            // Boundary regression guard for MUSCL reconstruction:
            //
            // When higher-order reconstruction is enabled, models conventionally use `grad_*`
            // state fields to reconstruct face states. On boundary faces, neighbor-side state
            // reads are replaced with Dirichlet/Neumann "ghost" values via `bc_kind/bc_value`.
            // If we also use non-zero neighbor-side gradients, the reconstruction step can modify
            // those ghost values and violate boundary semantics.
            //
            // To keep the IR PDE-agnostic and preserve existing BC semantics, treat neighbor-side
            // `grad_*` vectors as zero on boundary faces.
            //
            // Exception: for Rhie–Chow-style mass fluxes, `grad_p` participates in the HbyA
            // predictor. Its boundary projection is selected from the pressure BC kind by the
            // derived expression, so it must remain available whether pressure Dirichlet lives
            // on an inlet or an outlet. Prescribed-gradient boundaries use their compact
            // contribution directly and cannot inject an unmatched normal flux.
            if *side == FaceSide::Neighbor && field.starts_with("grad_") {
                let is_boundary = Expr::ident("is_boundary");
                let zero_cond = if field == "grad_p" {
                    Expr::from(false)
                } else {
                    is_boundary
                };
                return typed::VecExpr::<2>::from_components([
                    dsl::select(x, Expr::from(0.0), zero_cond.clone()),
                    dsl::select(y, Expr::from(0.0), zero_cond),
                ]);
            }

            typed::VecExpr::<2>::from_components([x, y])
        }
        FaceVec2Expr::CellStateVec2 { side, field } => {
            let idx = match side {
                FaceSide::Owner => Expr::ident("owner"),
                FaceSide::Neighbor => Expr::ident("neigh_idx"),
            };
            typed::VecExpr::<2>::from_components([
                state_component_at_resolver(
                    ctx.resolver,
                    "state",
                    idx.clone(),
                    field.as_str(),
                    XY::X.to_usize() as u32,
                ),
                state_component_at_resolver(
                    ctx.resolver,
                    "state",
                    idx,
                    field.as_str(),
                    XY::Y.to_usize() as u32,
                ),
            ])
        }
        FaceVec2Expr::Add(a, b) => {
            let a = lower_vec2(a, ctx, cse);
            let b = lower_vec2(b, ctx, cse);
            a.add(&b)
        }
        FaceVec2Expr::Sub(a, b) => {
            // DSL-aware geometry simplification:
            //   (face - center_a) - (face - center_b) == center_b - center_a
            // This pattern appears frequently in gradient approximations and QUICK stencils.
            if let (
                FaceVec2Expr::Builtin(FaceVec2Builtin::CellToFace { side: a_side }),
                FaceVec2Expr::Builtin(FaceVec2Builtin::CellToFace { side: b_side }),
            ) = (&**a, &**b)
            {
                let center_for = |side: FaceSide| match side {
                    FaceSide::Owner => Expr::ident("c_owner_vec"),
                    FaceSide::Neighbor => Expr::ident("c_neigh_cell_vec"),
                };
                let a_center = typed::VecExpr::<2>::from_expr(center_for(*a_side));
                let b_center = typed::VecExpr::<2>::from_expr(center_for(*b_side));
                return b_center.sub(&a_center);
            }

            let a = lower_vec2(a, ctx, cse);
            let b = lower_vec2(b, ctx, cse);
            a.sub(&b)
        }
        FaceVec2Expr::Neg(a) => lower_vec2(a, ctx, cse).neg(),
        FaceVec2Expr::MulScalar(v, s) => {
            lower_vec2(v, ctx, cse).mul_scalar(lower_scalar(s, ctx, cse))
        }
        FaceVec2Expr::Lerp(a, b) => {
            let a = lower_vec2(a, ctx, cse);
            let b = lower_vec2(b, ctx, cse);
            let l = Expr::ident("lambda");
            let lo = Expr::ident("lambda_other");
            a.mul_scalar(l).add(&b.mul_scalar(lo))
        }
    }
}

/// Trait for resolving field offsets in state layout.
/// Abstracts over PortRegistry (runtime) and StateLayout (build script).
trait OffsetResolver {
    fn component_offset(&self, field: &str, component: u32) -> Option<u32>;
    fn stride(&self) -> u32;
    fn field_kind(&self, field: &str) -> Option<FieldKind>;
}

impl OffsetResolver for ResolvedSlotResolver {
    fn component_offset(&self, field: &str, component: u32) -> Option<u32> {
        self.offsets.get(&(field.to_string(), component)).copied()
    }

    fn stride(&self) -> u32 {
        self.stride
    }

    fn field_kind(&self, field: &str) -> Option<FieldKind> {
        self.field_kinds.get(field).map(|k| match k {
            PortFieldKind::Scalar => FieldKind::Scalar,
            PortFieldKind::Vector2 => FieldKind::Vector2,
            PortFieldKind::Vector3 => FieldKind::Vector3,
        })
    }
}

fn state_component_at_resolver(
    resolver: &dyn OffsetResolver,
    buffer: &str,
    idx: Expr,
    field: &str,
    component: u32,
) -> Expr {
    let offset = resolver
        .component_offset(field, component)
        .unwrap_or_else(|| {
            panic!(
                "missing field '{}' component {} in state layout",
                field, component
            )
        });
    let stride = resolver.stride();
    Expr::ident(buffer).index(idx * stride + offset)
}

fn state_component_at_side_resolver(
    resolver: &dyn OffsetResolver,
    buffer: &str,
    side: FaceSide,
    field: &str,
    component: u32,
    flux_layout: &FluxLayout,
    structured: bool,
) -> Expr {
    let owner =
        state_component_at_resolver(resolver, buffer, Expr::ident("owner"), field, component);

    // Interior neighbor value (for boundary faces, `neigh_idx` is set to `owner`).
    let interior =
        state_component_at_resolver(resolver, buffer, Expr::ident("neigh_idx"), field, component);

    let Some(state_field_kind) = resolver.field_kind(field) else {
        panic!("missing field '{field}' in state layout");
    };
    let comp_name = match state_field_kind {
        FieldKind::Scalar => {
            if component != 0 {
                return owner;
            }
            field.to_string()
        }
        FieldKind::Vector2 => {
            if component > 1 {
                return owner;
            }
            let suffix = XY::from_index(component).suffix();
            format!("{field}_{suffix}")
        }
        FieldKind::Vector3 => {
            let suffix = match component {
                0 => "x",
                1 => "y",
                2 => "z",
                _ => return owner,
            };
            format!("{field}_{suffix}")
        }
    };

    if let Some(unknown_offset) = flux_layout.offset_for(&comp_name) {
        // The boundary BC table is keyed per-FACE. In the structured (cell-dispatched)
        // lowering the face id is `sfd_face_id = idx*4 + k`; only the unstructured
        // (face-dispatched) path has `idx` == face. Keying by `idx` in the structured
        // path reads a wrong (usually interior, kind=0) slot, so a Dirichlet inlet's
        // continuity face flux never sees the prescribed velocity — the channel then
        // under-conserves mass. Match `face_boundary[sfd_face_id]` (and the structured
        // assembly / grad_p_update / bc_expr, which all key by the face id).
        let bc_face_idx = if structured {
            Expr::ident("sfd_face_id")
        } else {
            Expr::ident("idx")
        };
        let bc = BcTable::new(bc_face_idx, Expr::from(flux_layout.stride));
        let kind = bc.kind_raw(Expr::from(unknown_offset));
        let value = bc.value(Expr::from(unknown_offset));

        let base = if side == FaceSide::Owner {
            // OpenFOAM's `fvc::interpolate(...)` sets non-coupled patch face values to the patch
            // field value directly, independent of the upwind direction. Mirror this by applying
            // the boundary condition to the owner-side evaluation as well, so that boundary faces
            // see identical left/right states (and thus no artificial dissipation across the
            // boundary).
            Expr::call_named(
                "bc_neighbor_scalar",
                vec![
                    owner.clone(),
                    owner.clone(),
                    kind,
                    value,
                    Expr::ident("d_own"),
                    Expr::ident("is_boundary"),
                ],
            )
        } else {
            Expr::call_named(
                "bc_neighbor_scalar",
                vec![
                    interior,
                    owner.clone(),
                    kind,
                    value,
                    Expr::ident("d_own"),
                    Expr::ident("is_boundary"),
                ],
            )
        };

        return apply_slipwall_velocity_reflection_resolver(
            resolver, buffer, field, component, base,
        );
    }

    if side == FaceSide::Owner {
        // No BC entry (auxiliary state): boundary faces use the owner cell value on both sides.
        return owner;
    }

    let base = dsl::select(interior, owner, Expr::ident("is_boundary"));
    apply_slipwall_velocity_reflection_resolver(resolver, buffer, field, component, base)
}

fn apply_slipwall_velocity_reflection_resolver(
    resolver: &dyn OffsetResolver,
    buffer: &str,
    field: &str,
    component: u32,
    base: Expr,
) -> Expr {
    // SlipWall boundary conditions are not representable as per-component Dirichlet/Neumann.
    // Emulate OpenFOAM `type slip` (basicSymmetry) by projecting out the normal component at
    // boundary faces:
    //   u_patch = u_owner - (u_owner · n) n
    //
    // This ensures no-penetration (zero normal mass flux) while preserving tangential velocity.
    let is_velocity_field = matches!(field, "u" | "U" | "rho_u" | "rhoU");
    if !is_velocity_field || component > 1 {
        return base;
    }
    let axis = XY::from_index(component);

    let is_boundary = Expr::ident("is_boundary");
    let boundary_type = Expr::ident("boundary_type");

    // SlipWall: enforce no-penetration for convective fluxes by projecting out the
    // normal component at boundary faces:
    //   u_patch = u_owner - (u_owner · n) n
    //
    // For Wall (no-slip) boundaries, respect the scalar BC table (typically Dirichlet=0 for
    // both components). Projecting the owner-cell velocity would incorrectly introduce
    // tangential slip into the convective flux.
    let is_slipwall = is_boundary & boundary_type.eq(Expr::from(4u32));
    let ux = state_component_at_resolver(
        resolver,
        buffer,
        Expr::ident("owner"),
        field,
        XY::X.to_usize() as u32,
    );
    let uy = state_component_at_resolver(
        resolver,
        buffer,
        Expr::ident("owner"),
        field,
        XY::Y.to_usize() as u32,
    );
    let nx = Expr::ident("normal_vec").clone().field("x");
    let ny = Expr::ident("normal_vec").field("y");
    let un = ux.clone() * nx.clone() + uy.clone() * ny.clone();

    let slip_projected = match axis {
        XY::X => ux - un * nx,
        XY::Y => uy - un * ny,
    };

    dsl::select(base, slip_projected, is_slipwall)
}

/// `CFD2_KGEN_PROFILE` counters: cumulative `lower_scalar` /
/// `lower_primitive_expr_at_side` invocations (relaxed; diagnostics only).
/// The lower_scalar count is the canonical "how much tree did we
/// materialize" metric for the flux-module lowering.
pub(crate) static KGEN_LS: std::sync::atomic::AtomicU64 = std::sync::atomic::AtomicU64::new(0);
pub(crate) static KGEN_LP: std::sync::atomic::AtomicU64 = std::sync::atomic::AtomicU64::new(0);

fn lower_scalar<'a>(
    expr: &'a FaceScalarExpr,
    ctx: &LowerCtx<'a>,
    cse: &mut FaceCseScope<'a>,
) -> Expr {
    KGEN_LS.fetch_add(1, std::sync::atomic::Ordering::Relaxed);
    if let Some(hit) = cse.memo_hit(expr) {
        return hit;
    }
    let lowered = match expr {
        FaceScalarExpr::Literal(v) => Expr::lit_f32(*v),
        FaceScalarExpr::Builtin(b) => match b {
            FaceScalarBuiltin::Area => Expr::ident("area"),
            FaceScalarBuiltin::Dist => Expr::ident("dist"),
            FaceScalarBuiltin::Lambda => Expr::ident("lambda"),
            FaceScalarBuiltin::LambdaOther => Expr::ident("lambda_other"),
            FaceScalarBuiltin::IsBoundary => dsl::select(0.0, 1.0, Expr::ident("is_boundary")),
        },
        FaceScalarExpr::Constant { name } => Expr::ident("constants").field(name.clone()),
        FaceScalarExpr::LowMachParam(param) => match param {
            LowMachParam::Model => {
                Expr::call_named("f32", vec![Expr::ident("low_mach_params").field("model")])
            }
            LowMachParam::ThetaFloor => Expr::ident("low_mach_params").field("theta_floor"),
            LowMachParam::PressureCouplingAlpha => {
                Expr::ident("low_mach_params").field("pressure_coupling_alpha")
            }
            LowMachParam::Eps4 => Expr::ident("low_mach_params").field("eps4"),
        },
        FaceScalarExpr::State { side, name } => ctx.state_scalar(*side, name.as_str(), 0),
        FaceScalarExpr::CellState { side, name } => {
            let idx = match side {
                FaceSide::Owner => Expr::ident("owner"),
                FaceSide::Neighbor => Expr::ident("neigh_idx"),
            };
            state_component_at_resolver(ctx.resolver, "state", idx, name.as_str(), 0)
        }
        FaceScalarExpr::BoundaryDirichlet { name } => {
            let unknown_offset = ctx.flux_layout.offset_for(name).unwrap_or_else(|| {
                panic!(
                    "boundary Dirichlet query field '{}' is not a coupled flux unknown",
                    name
                )
            });
            let bc_face_idx = if ctx.structured {
                Expr::ident("sfd_face_id")
            } else {
                Expr::ident("idx")
            };
            let bc = BcTable::new(bc_face_idx, Expr::from(ctx.flux_layout.stride));
            let is_dirichlet = Expr::ident("is_boundary")
                & bc
                    .kind_raw(Expr::from(unknown_offset))
                    .eq(Expr::from(1u32));
            dsl::select(0.0, 1.0, is_dirichlet)
        }
        FaceScalarExpr::Primitive { side, name } => {
            let prim = ctx.primitives.get(name.as_str()).unwrap_or_else(|| {
                panic!("primitive '{}' not found in PrimitiveDerivations", name)
            });
            lower_primitive_expr_at_side(prim, ctx, *side)
        }
        FaceScalarExpr::Add(a, b) => lower_scalar(a, ctx, cse) + lower_scalar(b, ctx, cse),
        FaceScalarExpr::Sub(a, b) => lower_scalar(a, ctx, cse) - lower_scalar(b, ctx, cse),
        FaceScalarExpr::Mul(a, b) => lower_scalar(a, ctx, cse) * lower_scalar(b, ctx, cse),
        FaceScalarExpr::Div(a, b) => lower_scalar(a, ctx, cse) / lower_scalar(b, ctx, cse),
        FaceScalarExpr::Neg(a) => -lower_scalar(a, ctx, cse),
        FaceScalarExpr::Abs(a) => dsl::abs(lower_scalar(a, ctx, cse)),
        FaceScalarExpr::Sqrt(a) => Expr::call_named("sqrt", vec![lower_scalar(a, ctx, cse)]),
        FaceScalarExpr::Max(a, b) => {
            dsl::max(lower_scalar(a, ctx, cse), lower_scalar(b, ctx, cse))
        }
        FaceScalarExpr::Min(a, b) => Expr::call_named(
            "min",
            vec![lower_scalar(a, ctx, cse), lower_scalar(b, ctx, cse)],
        ),
        FaceScalarExpr::Lerp(a, b) => {
            lower_scalar(a, ctx, cse) * Expr::ident("lambda")
                + lower_scalar(b, ctx, cse) * Expr::ident("lambda_other")
        }
        FaceScalarExpr::Dot(a, b) => {
            let a = lower_vec2(a, ctx, cse);
            let b = lower_vec2(b, ctx, cse);
            a.dot(&b)
        }
        // ALE volumetric mesh flux for this face (owner-signed, like `fluxes`).
        // The flux module is face-dispatched, so `idx` IS the face index. Only
        // ALE models' flux specs may reference it (gates the `mesh_fluxes`
        // binding); no structured model is ALE, so the structured lowering
        // (cell-dispatched, no `mesh_fluxes` buffer) rejects it outright.
        FaceScalarExpr::MeshFlux => {
            assert!(
                !ctx.structured,
                "FaceScalarExpr::MeshFlux is not available in STRUCTURED flux kernels \
                 (no structured ALE model exists; the structured grid has no mesh_fluxes buffer)"
            );
            dsl::array_access("mesh_fluxes", Expr::ident("idx"))
        }
    };
    cse.maybe_hoist(expr, lowered)
}

fn flux_spec_uses_low_mach(spec: &FluxModuleKernelSpec) -> bool {
    match spec {
        FluxModuleKernelSpec::ScalarReplicated { phi } => scalar_uses_low_mach(phi),
        FluxModuleKernelSpec::ScalarPerComponent { flux, .. } => {
            flux.iter().any(scalar_uses_low_mach)
        }
        FluxModuleKernelSpec::CentralUpwind {
            u_left,
            u_right,
            flux_left,
            flux_right,
            a_plus,
            a_minus,
            ..
        } => {
            u_left.iter().any(scalar_uses_low_mach)
                || u_right.iter().any(scalar_uses_low_mach)
                || flux_left.iter().any(scalar_uses_low_mach)
                || flux_right.iter().any(scalar_uses_low_mach)
                || scalar_uses_low_mach(a_plus)
                || scalar_uses_low_mach(a_minus)
        }
    }
}

fn vec2_uses_low_mach(expr: &FaceVec2Expr) -> bool {
    match expr {
        FaceVec2Expr::Builtin(_)
        | FaceVec2Expr::StateVec2 { .. }
        | FaceVec2Expr::CellStateVec2 { .. } => false,
        FaceVec2Expr::Vec2(x, y) => scalar_uses_low_mach(x) || scalar_uses_low_mach(y),
        FaceVec2Expr::Add(a, b) | FaceVec2Expr::Sub(a, b) | FaceVec2Expr::Lerp(a, b) => {
            vec2_uses_low_mach(a) || vec2_uses_low_mach(b)
        }
        FaceVec2Expr::Neg(a) => vec2_uses_low_mach(a),
        FaceVec2Expr::MulScalar(a, b) => vec2_uses_low_mach(a) || scalar_uses_low_mach(b),
    }
}

fn scalar_uses_low_mach(expr: &FaceScalarExpr) -> bool {
    match expr {
        FaceScalarExpr::LowMachParam(_) => true,
        FaceScalarExpr::Literal(_)
        | FaceScalarExpr::Builtin(_)
        | FaceScalarExpr::Constant { .. }
        | FaceScalarExpr::State { .. }
        | FaceScalarExpr::CellState { .. }
        | FaceScalarExpr::BoundaryDirichlet { .. }
        | FaceScalarExpr::Primitive { .. }
        | FaceScalarExpr::MeshFlux => false,
        FaceScalarExpr::Add(a, b)
        | FaceScalarExpr::Sub(a, b)
        | FaceScalarExpr::Mul(a, b)
        | FaceScalarExpr::Div(a, b)
        | FaceScalarExpr::Max(a, b)
        | FaceScalarExpr::Min(a, b)
        | FaceScalarExpr::Lerp(a, b) => scalar_uses_low_mach(a) || scalar_uses_low_mach(b),
        FaceScalarExpr::Neg(a) | FaceScalarExpr::Abs(a) | FaceScalarExpr::Sqrt(a) => {
            scalar_uses_low_mach(a)
        }
        FaceScalarExpr::Dot(a, b) => vec2_uses_low_mach(a) || vec2_uses_low_mach(b),
    }
}

