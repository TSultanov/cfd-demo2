/// Build a resolver from ResolvedStateSlotsSpec.
struct ResolvedSlotResolver {
    stride: u32,
    offsets: HashMap<(String, u32), u32>,
    field_kinds: HashMap<String, PortFieldKind>,
}

impl ResolvedSlotResolver {
    fn from_spec(spec: &ResolvedStateSlotsSpec) -> Self {
        let mut offsets = HashMap::new();
        let mut field_kinds = HashMap::new();

        for slot in &spec.slots {
            field_kinds.insert(slot.name.clone(), slot.kind);
            let count = slot.kind.component_count();
            for comp in 0..count {
                offsets.insert((slot.name.clone(), comp), slot.base_offset + comp);
            }
        }

        Self {
            stride: spec.stride,
            offsets,
            field_kinds,
        }
    }
}

fn validate_face_channel_layout(
    flux_layout: &FluxLayout,
    face_channels: &ExplicitFaceChannelLiveness,
    flux_stride: u32,
) {
    assert_eq!(
        face_channels.coupled_stride(),
        flux_layout.stride,
        "face-channel liveness must cover the semantic FluxLayout"
    );
    assert_eq!(
        flux_stride,
        face_channels.storage_stride(),
        "flux_stride must match compact live face-channel storage"
    );
}

#[cfg(test)]
#[allow(clippy::too_many_arguments)]
pub fn generate_flux_module_wgsl(
    resolved_slots: &ResolvedStateSlotsSpec,
    flux_layout: &FluxLayout,
    face_channels: &ExplicitFaceChannelLiveness,
    flux_stride: u32,
    primitives: &[(String, Expr)],
    spec: &FluxModuleKernelSpec,
    eos_params: &[ParamSpec],
    structured: bool,
) -> KernelWgsl {
    assert!(flux_stride > 0, "flux_module requires flux_stride > 0");
    validate_face_channel_layout(flux_layout, face_channels, flux_stride);

    let primitive_map: HashMap<&str, &Expr> =
        primitives.iter().map(|(k, v)| (k.as_str(), v)).collect();

    let resolver = ResolvedSlotResolver::from_spec(resolved_slots);
    let resolver_ref: &dyn OffsetResolver = &resolver;

    let mut module = Module::new();
    module.push(Item::Comment(
        "GENERATED BY CFD2 CODEGEN (flux_module)".to_string(),
    ));
    module.push(Item::Comment("DO NOT EDIT MANUALLY".to_string()));
    module.extend(base_items(
        flux_spec_uses_low_mach(spec),
        flux_spec_uses_mesh_flux(spec),
        eos_params,
        structured,
    ));
    module.push(Item::Function(main_fn(
        resolver_ref,
        flux_layout,
        face_channels,
        flux_stride,
        &primitive_map,
        spec,
        structured,
    )));
    KernelWgsl::from(module)
}

/// Render the `bc_neighbor_scalar` helper as a standalone WGSL function string.
fn render_bc_neighbor_scalar_helper() -> String {
    let mut helper_module = Module::new();
    helper_module.push(Item::Function(bc_neighbor_scalar_fn()));
    helper_module.to_wgsl()
}

/// Extract Pattern B launch semantics from a main function body.
///
/// Pattern B:
///   stmt 0: `let idx = <invocation_index_expr>`
///   stmt 1: `if (<bounds_check_expr>) { return; }`
fn extract_launch_pattern_b(main: &Function) -> Result<(LaunchSemantics, usize), String> {
    let idx_expr = match main.body.stmts.first() {
        Some(Stmt::Let { name, expr, .. }) if name == "idx" => expr.to_string(),
        _ => {
            return Err(
                "flux_module: expected first statement to define idx launch expression".to_string(),
            );
        }
    };

    let bounds_check = match main.body.stmts.get(1) {
        Some(Stmt::If {
            cond,
            then_block,
            else_block,
        }) if else_block.is_none()
            && then_block.stmts.len() == 1
            && matches!(then_block.stmts.first(), Some(Stmt::Return(None))) =>
        {
            cond.to_string()
        }
        _ => {
            return Err(
                "flux_module: expected second statement to be bounds guard if-return".to_string(),
            );
        }
    };

    let launch = LaunchSemantics::new([64, 1, 1], idx_expr, Some(bounds_check));
    Ok((launch, 2))
}

/// Build a KernelProgram from a single-scheme flux module spec.
#[allow(clippy::too_many_arguments)]
pub fn generate_flux_module_kernel_program(
    id: &str,
    resolved_slots: &ResolvedStateSlotsSpec,
    flux_layout: &FluxLayout,
    face_channels: &ExplicitFaceChannelLiveness,
    flux_stride: u32,
    primitives: &[(String, Expr)],
    spec: &FluxModuleKernelSpec,
    eos_params: &[ParamSpec],
    structured: bool,
) -> Result<KernelProgram, String> {
    assert!(flux_stride > 0, "flux_module requires flux_stride > 0");
    validate_face_channel_layout(flux_layout, face_channels, flux_stride);

    let uses_low_mach = flux_spec_uses_low_mach(spec);
    let items = base_items(
        uses_low_mach,
        flux_spec_uses_mesh_flux(spec),
        eos_params,
        structured,
    );
    let bindings =
        cfd2_codegen::solver::codegen::coupled_common::kernel_bindings_from_items(&items)?;

    let primitive_map: HashMap<&str, &Expr> =
        primitives.iter().map(|(k, v)| (k.as_str(), v)).collect();

    let resolver = ResolvedSlotResolver::from_spec(resolved_slots);
    let resolver_ref: &dyn OffsetResolver = &resolver;

    let main = main_fn(
        resolver_ref,
        flux_layout,
        face_channels,
        flux_stride,
        &primitive_map,
        spec,
        structured,
    );
    let (launch, skip) = extract_launch_pattern_b(&main)?;

    let kernel_stmts = &main.body.stmts[skip..];

    let helper = render_bc_neighbor_scalar_helper();

    // Structured flux is CELL-dispatched (4 fluxes/cell); unstructured is per
    // physical face.
    let dispatch = if structured {
        DispatchDomain::Cells
    } else {
        DispatchDomain::Faces
    };
    let mut program = KernelProgram::new(id, dispatch, launch, bindings);
    program.helper_functions = vec![helper];
    program.body = kernel_stmts.to_vec();
    program.eos_params = eos_params.to_vec();
    Ok(program)
}

/// Build a KernelProgram from a runtime-scheme flux module spec.
#[allow(clippy::too_many_arguments)]
pub fn generate_flux_module_kernel_program_runtime_scheme(
    id: &str,
    resolved_slots: &ResolvedStateSlotsSpec,
    flux_layout: &FluxLayout,
    face_channels: &ExplicitFaceChannelLiveness,
    flux_stride: u32,
    primitives: &[(String, Expr)],
    variants: &[(Scheme, FluxModuleKernelSpec)],
    eos_params: &[ParamSpec],
    structured: bool,
) -> Result<KernelProgram, String> {
    assert!(flux_stride > 0, "flux_module requires flux_stride > 0");
    validate_face_channel_layout(flux_layout, face_channels, flux_stride);

    let uses_low_mach = variants
        .iter()
        .any(|(_, spec)| flux_spec_uses_low_mach(spec));
    let uses_mesh_flux = variants
        .iter()
        .any(|(_, spec)| flux_spec_uses_mesh_flux(spec));
    let items = base_items(uses_low_mach, uses_mesh_flux, eos_params, structured);
    let bindings =
        cfd2_codegen::solver::codegen::coupled_common::kernel_bindings_from_items(&items)?;

    let primitive_map: HashMap<&str, &Expr> =
        primitives.iter().map(|(k, v)| (k.as_str(), v)).collect();

    let resolver = ResolvedSlotResolver::from_spec(resolved_slots);
    let resolver_ref: &dyn OffsetResolver = &resolver;

    let profile = std::env::var("CFD2_KGEN_PROFILE").is_ok();
    let t = std::time::Instant::now();
    let main = main_fn_runtime_scheme(
        resolver_ref,
        flux_layout,
        face_channels,
        flux_stride,
        &primitive_map,
        variants,
        structured,
    );
    if profile {
        eprintln!(
            "[kgen]   main_fn_runtime_scheme: {:.0} ms ({} top-level stmts) | \
             lower_scalar calls={} lower_primitive calls={}",
            t.elapsed().as_secs_f64() * 1e3,
            main.body.stmts.len(),
            KGEN_LS.load(std::sync::atomic::Ordering::Relaxed),
            KGEN_LP.load(std::sync::atomic::Ordering::Relaxed)
        );
    }
    let t = std::time::Instant::now();
    let (launch, skip) = extract_launch_pattern_b(&main)?;
    if profile {
        eprintln!(
            "[kgen]   extract_launch_pattern_b: {:.0} ms",
            t.elapsed().as_secs_f64() * 1e3
        );
    }

    let kernel_stmts = &main.body.stmts[skip..];

    let helper = render_bc_neighbor_scalar_helper();

    let dispatch = if structured {
        DispatchDomain::Cells
    } else {
        DispatchDomain::Faces
    };

    let mut program = KernelProgram::new(id, dispatch, launch, bindings);
    program.helper_functions = vec![helper];
    program.body = kernel_stmts.to_vec();
    program.eos_params = eos_params.to_vec();
    Ok(program)
}

