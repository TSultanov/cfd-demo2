fn main_body(
    resolver: &dyn OffsetResolver,
    flux_layout: &FluxLayout,
    face_channels: &ExplicitFaceChannelLiveness,
    flux_stride: u32,
    primitives: &HashMap<&str, &Expr>,
    spec: &FluxModuleKernelSpec,
    structured: bool,
) -> Block {
    if structured {
        return structured_main_body(
            resolver,
            flux_layout,
            face_channels,
            flux_stride,
            primitives,
            spec,
        );
    }
    let mut stmts = vec![
        dsl::let_expr(
            "idx",
            Expr::ident("global_id").field("y") * Expr::ident("constants").field("stride_x")
                + Expr::ident("global_id").field("x"),
        ),
        dsl::if_block_expr(
            Expr::ident("idx").ge(Expr::call_named(
                "arrayLength",
                vec![Expr::ident("face_areas").addr_of()],
            )),
            dsl::block(vec![Stmt::Return(None)]),
            None,
        ),
        dsl::let_expr("owner", dsl::array_access("face_owner", Expr::ident("idx"))),
        dsl::let_expr(
            "neighbor",
            dsl::array_access("face_neighbor", Expr::ident("idx")),
        ),
        dsl::let_expr("is_boundary", Expr::ident("neighbor").eq(-1)),
        // For boundary faces, we treat the "neighbor" side as the owner cell (zero-gradient
        // extrapolation). Boundary-aware flux formulas can still use `boundary_type`.
        dsl::var_typed_expr("neigh_idx", Type::U32, Some(Expr::ident("owner"))),
        dsl::if_block_expr(
            Expr::ident("neighbor").ne(-1),
            dsl::block(vec![dsl::assign_expr(
                Expr::ident("neigh_idx"),
                Expr::call_named("u32", vec![Expr::ident("neighbor")]),
            )]),
            None,
        ),
        dsl::let_expr("area", dsl::array_access("face_areas", Expr::ident("idx"))),
    ];
    stmts.push(dsl::let_expr(
        "boundary_type",
        dsl::array_access("face_boundary", Expr::ident("idx")),
    ));
    stmts.push(dsl::let_expr(
        "face_center",
        dsl::array_access("face_centers", Expr::ident("idx")),
    ));

    stmts.push(dsl::var_typed_expr(
        "normal_vec",
        Type::vec2_f32(),
        Some(
            typed::VecExpr::<2>::from_xy_fields(
                Expr::ident("face_normals").index(Expr::ident("idx")),
            )
            .expr(),
        ),
    ));

    stmts.push(dsl::let_expr(
        "c_owner",
        dsl::array_access("cell_centers", Expr::ident("owner")),
    ));
    stmts.push(dsl::let_typed_expr(
        "c_owner_vec",
        Type::vec2_f32(),
        typed::VecExpr::<2>::from_xy_fields(Expr::ident("c_owner")).expr(),
    ));
    stmts.push(dsl::let_typed_expr(
        "face_center_vec",
        Type::vec2_f32(),
        typed::VecExpr::<2>::from_xy_fields(Expr::ident("face_center")).expr(),
    ));

    // Ensure the face normal is oriented outward from the owner cell.
    let owner_face_d_vec = typed::VecExpr::<2>::from_expr(Expr::ident("face_center_vec"))
        .sub(&typed::VecExpr::<2>::from_expr(Expr::ident("c_owner_vec")));
    stmts.push(dsl::if_block_expr(
        owner_face_d_vec
            .dot(&typed::VecExpr::<2>::from_expr(Expr::ident("normal_vec")))
            .lt(0.0),
        dsl::block(vec![dsl::assign_expr(
            Expr::ident("normal_vec"),
            typed::VecExpr::<2>::from_expr(Expr::ident("normal_vec"))
                .neg()
                .expr(),
        )]),
        None,
    ));

    stmts.extend(face_stmts(
        resolver,
        flux_layout,
        face_channels,
        flux_stride,
        primitives,
        spec,
        false,
    ));

    Block::new(stmts)
}

/// Structured (Cartesian) flux module body: CELL-dispatched, computing the 4
/// per-cell face fluxes into `fluxes[(idx*4+k)*stride + c]` (the layout the
/// structured assembly reads). Binds the SAME face locals the unstructured
/// prologue does — but from `grid` arithmetic (`sfd_*`), no connectivity — so
/// the shared `face_stmts` Rhie–Chow / central-upwind physics is reused verbatim.
fn structured_main_body(
    resolver: &dyn OffsetResolver,
    flux_layout: &FluxLayout,
    face_channels: &ExplicitFaceChannelLiveness,
    flux_stride: u32,
    primitives: &HashMap<&str, &Expr>,
    spec: &FluxModuleKernelSpec,
) -> Block {
    let mut stmts = vec![
        dsl::let_expr(
            "idx",
            Expr::ident("global_id").field("y") * Expr::ident("constants").field("stride_x")
                + Expr::ident("global_id").field("x"),
        ),
        sg::structured_bound_guard(),
    ];
    stmts.extend(sg::structured_cell_geom());

    let mut face_body = sg::structured_face_locals();
    // Alias the sfd_* descriptor to the names `face_stmts` consumes. On a
    // structured cell, the face belongs to `idx` with an outward normal, so
    // `owner == idx` and no orientation flip is needed.
    face_body.push(dsl::let_expr("owner", Expr::ident("idx")));
    face_body.push(dsl::let_expr("neigh_idx", Expr::ident("sfd_other_idx")));
    face_body.push(dsl::let_expr("is_boundary", Expr::ident("sfd_is_boundary")));
    face_body.push(dsl::let_expr("area", Expr::ident("sfd_area")));
    // SlipWall (type 4) is not yet represented structured; a neutral tag keeps
    // the flux on its default (Dirichlet/Neumann-via-bc) boundary path.
    face_body.push(dsl::let_expr("boundary_type", sg::structured_boundary_type()));
    face_body.push(dsl::let_expr(
        "face_center",
        sg::sfd_vector2("sfd_face_cx", "sfd_face_cy"),
    ));
    face_body.push(dsl::let_typed_expr(
        "normal_vec",
        Type::vec2_f32(),
        sg::sfd_vec2("sfd_normal_x", "sfd_normal_y"),
    ));
    face_body.push(dsl::let_expr(
        "c_owner",
        sg::sfd_vector2("sfd_cx", "sfd_cy"),
    ));
    face_body.push(dsl::let_typed_expr(
        "c_owner_vec",
        Type::vec2_f32(),
        sg::sfd_vec2("sfd_cx", "sfd_cy"),
    ));
    face_body.push(dsl::let_typed_expr(
        "face_center_vec",
        Type::vec2_f32(),
        sg::sfd_vec2("sfd_face_cx", "sfd_face_cy"),
    ));
    face_body.extend(face_stmts(
        resolver,
        flux_layout,
        face_channels,
        flux_stride,
        primitives,
        spec,
        true,
    ));

    stmts.push(dsl::for_loop_expr(
        dsl::for_init_var_expr("k", Expr::from(0u32)),
        Expr::ident("k").lt(Expr::from(4u32)),
        dsl::for_step_increment_expr(Expr::ident("k")),
        dsl::block(face_body),
    ));

    Block::new(stmts)
}

