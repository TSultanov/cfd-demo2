pub fn generate_packed_state_gradients_wgsl(
    layout: &StateLayout,
    unknown_state_offsets: &[u32],
    eos_params: &[ParamSpec],
    knob_gated: bool,
) -> Result<KernelWgsl, String> {
    validate_unknown_offsets(layout, unknown_state_offsets)?;

    let mut module = Module::new();
    module.push(Item::Comment(
        "GENERATED BY CFD2 CODEGEN (packed_state_gradients)".to_string(),
    ));
    module.push(Item::Comment("DO NOT EDIT MANUALLY".to_string()));
    module.extend(base_items(eos_params));
    module.push(Item::Function(main_fn(
        layout,
        unknown_state_offsets,
        knob_gated,
    )));
    Ok(KernelWgsl::from(module))
}

/// The `grad_state` buffer is keyed by STATE OFFSET (stride = state stride):
/// the assembly's reconstruction reads the gradient of unknown `k` at
/// `cell * stride + state_offset(k)`. The writer must use the same key — and
/// must read the unknown's VALUES from the same state offset. Boundary
/// tables, by contrast, are indexed by unknown RANK. For models whose solved
/// unknowns are a prefix of the state layout the two keys coincide; the
/// first model with an unknown placed after auxiliary fields (buoyant
/// temperature at offset 8 behind d_p/grad_p) exposed the writer using rank
/// where offset was required — its gradient slot was never written and the
/// reconstruction silently degraded to first-order upwind.
fn validate_unknown_offsets(
    layout: &StateLayout,
    unknown_state_offsets: &[u32],
) -> Result<(), String> {
    let stride = layout.stride();
    if unknown_state_offsets.is_empty() {
        return Err("packed_state_gradients requires at least one unknown".to_string());
    }
    if let Some(&bad) = unknown_state_offsets.iter().find(|&&o| o >= stride) {
        return Err(format!(
            "packed_state_gradients: unknown state offset {bad} out of range for state stride {stride}"
        ));
    }
    Ok(())
}

fn base_items(eos_params: &[ParamSpec]) -> Vec<Item> {
    let mut items = Vec::new();
    items.push(Item::Struct(vector2_struct()));
    items.push(Item::Struct(constants_struct(eos_params)));
    items.push(Item::Comment("Group 0: Mesh".to_string()));
    items.extend(mesh_bindings());
    items.push(Item::Comment("Group 1: Fields".to_string()));
    items.extend(state_bindings());
    items.push(Item::Comment(
        "Group 2: Boundary conditions (per face x unknown)".to_string(),
    ));
    items.extend(boundary_bindings());
    items
}

fn mesh_bindings() -> Vec<Item> {
    vec![
        storage_var("face_owner", Type::array(Type::U32), 0, 0, AccessMode::Read),
        storage_var(
            "face_neighbor",
            Type::array(Type::I32),
            0,
            1,
            AccessMode::Read,
        ),
        storage_var("face_areas", Type::array(Type::F32), 0, 2, AccessMode::Read),
        storage_var(
            "face_normals",
            Type::array(Type::Custom("Vector2".to_string())),
            0,
            3,
            AccessMode::Read,
        ),
        storage_var(
            "face_centers",
            Type::array(Type::Custom("Vector2".to_string())),
            0,
            13,
            AccessMode::Read,
        ),
        storage_var(
            "cell_centers",
            Type::array(Type::Custom("Vector2".to_string())),
            0,
            4,
            AccessMode::Read,
        ),
        storage_var("cell_vols", Type::array(Type::F32), 0, 5, AccessMode::Read),
        storage_var(
            "cell_face_offsets",
            Type::array(Type::U32),
            0,
            6,
            AccessMode::Read,
        ),
        storage_var("cell_faces", Type::array(Type::U32), 0, 7, AccessMode::Read),
    ]
}

fn state_bindings() -> Vec<Item> {
    vec![
        storage_var("state", Type::array(Type::F32), 1, 0, AccessMode::Read),
        uniform_var("constants", Type::Custom("Constants".to_string()), 1, 3),
        storage_var(
            "grad_state",
            Type::array(Type::Custom("Vector2".to_string())),
            1,
            4,
            AccessMode::ReadWrite,
        ),
    ]
}

fn main_fn(layout: &StateLayout, unknown_state_offsets: &[u32], knob_gated: bool) -> Function {
    let params = vec![Param::new(
        "global_id",
        Type::vec3_u32(),
        vec![Attribute::Builtin("global_invocation_id".to_string())],
    )];

    Function::new(
        "main",
        params,
        None,
        vec![Attribute::Compute, Attribute::WorkgroupSize(64)],
        main_body(layout, unknown_state_offsets, knob_gated),
    )
}

fn main_body(layout: &StateLayout, unknown_state_offsets: &[u32], knob_gated: bool) -> Block {
    let gradient_stmts = gradient_body_statements(layout, unknown_state_offsets);

    let mut stmts = vec![
        dsl::let_expr(
            "idx",
            Expr::ident("global_id").field("y") * Expr::ident("constants").field("stride_x")
                + Expr::ident("global_id").field("x"),
        ),
        dsl::if_block_expr(
            Expr::ident("idx").ge(Expr::call_named(
                "arrayLength",
                vec![Expr::ident("cell_vols").addr_of()],
            )),
            dsl::block(vec![Stmt::Return(None)]),
            None,
        ),
    ];

    if knob_gated {
        // Skip the full Green–Gauss pass for first-order upwind to keep overhead low.
        //
        // The skip is a *body-wrapping guard*, never an early `return`: this kernel is
        // fused with the assembly kernel, and an early return would abort the fused
        // kernel's remaining segments (observed as a frozen solver when the runtime
        // scheme knob is switched to Upwind on a grad-state recipe).
        //
        // Models that *declare* a non-upwind scheme on a convection term are generated
        // with `knob_gated = false`: their gradients are needed regardless of the knob.
        stmts.push(dsl::if_block_expr(
            Expr::ident("constants")
                .field("scheme")
                .ne(Expr::from(0u32)),
            dsl::block(gradient_stmts),
            None,
        ));
    } else {
        stmts.extend(gradient_stmts);
    }

    Block::new(stmts)
}

fn gradient_body_statements(layout: &StateLayout, unknown_state_offsets: &[u32]) -> Vec<Stmt> {
    let stride = layout.stride();
    let unknown_stride = unknown_state_offsets.len() as u32;

    let mut stmts = vec![
        dsl::let_expr(
            "cell_center",
            dsl::array_access("cell_centers", Expr::ident("idx")),
        ),
        dsl::let_typed_expr(
            "cell_center_vec",
            Type::vec2_f32(),
            typed::VecExpr::<2>::from_xy_fields(Expr::ident("cell_center")).expr(),
        ),
        dsl::let_expr("vol", dsl::array_access("cell_vols", Expr::ident("idx"))),
        dsl::let_expr(
            "start",
            dsl::array_access("cell_face_offsets", Expr::ident("idx")),
        ),
        dsl::let_expr(
            "end",
            dsl::array_access("cell_face_offsets", Expr::ident("idx") + 1u32),
        ),
    ];

    // Accumulators: one vec2 per coupled unknown component (named by rank).
    for component in 0..unknown_stride {
        let var_name = format!("grad_acc_{component}");
        stmts.push(dsl::var_typed_expr(
            &var_name,
            Type::vec2_f32(),
            Some(dsl::vec2_f32(0.0, 0.0)),
        ));
    }

    // Face loop.
    let face_loop_body = {
        let mut body = vec![
            dsl::let_expr(
                "face_idx",
                dsl::array_access("cell_faces", Expr::ident("k")),
            ),
            dsl::let_expr(
                "owner",
                dsl::array_access("face_owner", Expr::ident("face_idx")),
            ),
            dsl::let_expr(
                "neighbor_raw",
                dsl::array_access("face_neighbor", Expr::ident("face_idx")),
            ),
            dsl::let_expr("is_boundary", Expr::ident("neighbor_raw").eq(-1)),
        ];
        body.push(dsl::let_expr(
            "area",
            dsl::array_access("face_areas", Expr::ident("face_idx")),
        ));
        body.push(dsl::let_expr(
            "face_center",
            dsl::array_access("face_centers", Expr::ident("face_idx")),
        ));
        body.push(dsl::let_typed_expr(
            "face_center_vec",
            Type::vec2_f32(),
            typed::VecExpr::<2>::from_xy_fields(Expr::ident("face_center")).expr(),
        ));
        body.push(dsl::var_typed_expr(
            "normal_vec",
            Type::vec2_f32(),
            Some(
                typed::VecExpr::<2>::from_xy_fields(
                    Expr::ident("face_normals").index(Expr::ident("face_idx")),
                )
                .expr(),
            ),
        ));
        let cell_to_face = typed::VecExpr::<2>::from_expr(Expr::ident("face_center_vec")).sub(
            &typed::VecExpr::<2>::from_expr(Expr::ident("cell_center_vec")),
        );
        body.push(dsl::if_block_expr(
            cell_to_face
                .dot(&typed::VecExpr::<2>::from_expr(Expr::ident("normal_vec")))
                .lt(0.0),
            dsl::block(vec![dsl::assign_expr(
                Expr::ident("normal_vec"),
                typed::VecExpr::<2>::from_expr(Expr::ident("normal_vec"))
                    .neg()
                    .expr(),
            )]),
            None,
        ));

        body.push(dsl::var_typed_expr(
            "other_idx",
            Type::U32,
            Some(Expr::ident("idx")),
        ));
        body.push(dsl::var_typed_expr(
            "other_center_vec",
            Type::vec2_f32(),
            Some(Expr::ident("face_center_vec")),
        ));
        body.push(dsl::if_block_expr(
            Expr::ident("neighbor_raw").ne(-1),
            dsl::block(vec![
                dsl::let_expr(
                    "neighbor",
                    Expr::call_named("u32", vec![Expr::ident("neighbor_raw")]),
                ),
                dsl::assign_expr(Expr::ident("other_idx"), Expr::ident("neighbor")),
                dsl::if_block_expr(
                    Expr::ident("owner").ne(Expr::ident("idx")),
                    dsl::block(vec![dsl::assign_expr(
                        Expr::ident("other_idx"),
                        Expr::ident("owner"),
                    )]),
                    None,
                ),
                dsl::let_expr(
                    "other_center",
                    dsl::array_access("cell_centers", Expr::ident("other_idx")),
                ),
                dsl::assign_expr(
                    Expr::ident("other_center_vec"),
                    typed::VecExpr::<2>::from_xy_fields(Expr::ident("other_center")).expr(),
                ),
            ]),
            None,
        ));

        body.push(dsl::let_expr(
            "d_own",
            dsl::distance(
                Expr::ident("cell_center_vec"),
                Expr::ident("face_center_vec"),
            ),
        ));
        body.push(dsl::let_expr(
            "d_neigh",
            dsl::distance(
                Expr::ident("other_center_vec"),
                Expr::ident("face_center_vec"),
            ),
        ));
        body.push(dsl::let_expr(
            "total_dist",
            Expr::ident("d_own") + Expr::ident("d_neigh"),
        ));
        body.push(dsl::var_typed_expr("lambda", Type::F32, Some(0.5.into())));
        body.push(dsl::if_block_expr(
            Expr::ident("total_dist").gt(1e-6),
            dsl::block(vec![dsl::assign_expr(
                Expr::ident("lambda"),
                Expr::ident("d_neigh") / Expr::ident("total_dist"),
            )]),
            None,
        ));
        body.push(dsl::let_expr(
            "lambda_other",
            Expr::from(1.0) - Expr::ident("lambda"),
        ));

        // Values are read at the unknown's STATE OFFSET; boundary tables are
        // indexed by unknown RANK (`component`).
        for (component, &state_offset) in unknown_state_offsets.iter().enumerate() {
            let component = component as u32;
            let cell_val =
                Expr::ident("state").index(Expr::ident("idx") * stride + Expr::from(state_offset));
            let interior_other = Expr::ident("state")
                .index(Expr::ident("other_idx") * stride + Expr::from(state_offset));

            let bc = BcTable::new(Expr::ident("face_idx"), Expr::from(unknown_stride));
            let from_bc = bc.ghost_value(Expr::from(component), cell_val.clone(), Expr::ident("d_own"));

            let other_val = dsl::select(interior_other, from_bc, Expr::ident("is_boundary"));
            let phi_face =
                cell_val * Expr::ident("lambda") + other_val * Expr::ident("lambda_other");

            let acc_name = format!("grad_acc_{component}");
            let contrib = typed::VecExpr::<2>::from_expr(Expr::ident("normal_vec"))
                .mul_scalar(phi_face * Expr::ident("area"))
                .expr();
            body.push(dsl::assign_op_expr(
                AssignOp::Add,
                Expr::ident(acc_name),
                contrib,
            ));
        }

        dsl::block(body)
    };

    stmts.push(dsl::for_loop_expr(
        dsl::for_init_var_expr("k", Expr::ident("start")),
        Expr::ident("k").lt(Expr::ident("end")),
        dsl::for_step_increment_expr(Expr::ident("k")),
        face_loop_body,
    ));

    // Write out gradients (divide by volume) into the packed `grad_state`
    // buffer, keyed by the unknown's STATE OFFSET (the assembly reads the
    // gradient for unknown k at `cell * stride + state_offset(k)`).
    for (component, &state_offset) in unknown_state_offsets.iter().enumerate() {
        let acc_name = format!("grad_acc_{component}");
        let grad_vec = typed::VecExpr::<2>::from_expr(Expr::ident(acc_name))
            .mul_scalar(Expr::from(1.0) / dsl::max(Expr::ident("vol"), 1e-12))
            .expr();
        stmts.push(dsl::let_typed_expr(
            &format!("grad_out_{component}"),
            Type::vec2_f32(),
            grad_vec,
        ));

        let out = Expr::ident(format!("grad_out_{component}"));
        let out_idx = Expr::ident("idx") * stride + Expr::from(state_offset);
        stmts.push(dsl::assign_expr(
            Expr::ident("grad_state").index(out_idx.clone()).field("x"),
            out.clone().field("x"),
        ));
        stmts.push(dsl::assign_expr(
            Expr::ident("grad_state").index(out_idx).field("y"),
            out.field("y"),
        ));
    }

    stmts
}

const PACKED_STATE_GRADIENTS_WORKGROUP_SIZE: u32 = 64;

/// Extract `LaunchSemantics` from the first statements of the packed_state_gradients body.
///
/// The body starts with:
///   0: let idx = ...       (invocation index)
///   1: if (idx >= ...) { return; }  (bounds check)
///
/// Everything after these is the kernel body proper (which, for knob-gated models,
/// is a single `if (constants.scheme != 0u) { ... }` wrapping block — deliberately
/// not an early return so that fusion with downstream segments stays correct).
///
/// Returns (launch, consumed_stmts).
fn launch_from_gradient_statements(stmts: &[Stmt]) -> Result<(LaunchSemantics, usize), String> {
    // Statement 0: `let idx = ...`
    let idx_expr = match stmts.first() {
        Some(Stmt::Let { name, expr, .. }) if name == "idx" => expr.to_string(),
        _ => {
            return Err(
                "packed_state_gradients: expected first statement to define idx launch expression"
                    .to_string(),
            );
        }
    };

    // Statement 1: `if (idx >= arrayLength(...)) { return; }`
    let bounds_expr = match stmts.get(1) {
        Some(Stmt::If {
            cond,
            then_block,
            else_block,
        }) if else_block.is_none()
            && then_block.stmts.len() == 1
            && matches!(then_block.stmts.first(), Some(Stmt::Return(None))) =>
        {
            cond.to_string()
        }
        _ => {
            return Err(
                "packed_state_gradients: expected second statement to be idx bounds guard"
                    .to_string(),
            );
        }
    };

    Ok((
        LaunchSemantics::new(
            [PACKED_STATE_GRADIENTS_WORKGROUP_SIZE, 1, 1],
            idx_expr,
            Some(bounds_expr),
        ),
        2,
    ))
}

/// Generate a `KernelProgram` (DSL IR) for the packed_state_gradients kernel,
/// enabling fusion with adjacent DSL kernels.
pub fn generate_packed_state_gradients_kernel_program(
    id: &str,
    layout: &StateLayout,
    unknown_state_offsets: &[u32],
    eos_params: &[ParamSpec],
    knob_gated: bool,
) -> Result<KernelProgram, String> {
    validate_unknown_offsets(layout, unknown_state_offsets)?;

    let items = base_items(eos_params);
    let bindings = kernel_bindings_from_items(&items)?;
    let main = main_fn(layout, unknown_state_offsets, knob_gated);
    let (launch, consumed_stmts) = launch_from_gradient_statements(&main.body.stmts)?;
    let kernel_stmts = &main.body.stmts[consumed_stmts..];

    let mut program = KernelProgram::new(id, DispatchDomain::Cells, launch, bindings);
    program.body = kernel_stmts.to_vec();
    program.eos_params = eos_params.to_vec();

    // Side-effect metadata for hazard analysis.
    let mut read_set = BTreeSet::new();
    // Group 0: mesh buffers (all read-only)
    for binding_slot in [0u32, 1, 2, 3, 4, 5, 6, 7, 13] {
        read_set.insert(EffectResource::binding(0, binding_slot));
    }
    // Group 1: state (read), constants (uniform, read)
    read_set.insert(EffectResource::binding(1, 0));
    read_set.insert(EffectResource::binding(1, 3));
    // Group 2: bc_kind, bc_value (read-only)
    read_set.insert(EffectResource::binding(2, 0));
    read_set.insert(EffectResource::binding(2, 1));

    let mut write_set = BTreeSet::new();
    // Group 1: grad_state (read_write — output)
    write_set.insert(EffectResource::binding(1, 4));

    program.side_effects = SideEffectMetadata {
        read_set,
        write_set,
        uses_barriers: false,
        uses_atomics: false,
    };

    Ok(program)
}
